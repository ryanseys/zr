# Boot and the C entry point. The program supplies `zr_toplevel`.
Machine.import "zr_toplevel", [] => Value


sig [Word, Word, Value] => Value
machine def zr_boot_class(g, name, sup)
  c = zr_class_new(sup)
  zr_set_global(g, c)
  c
end

sig [Word, Word] => Void
machine def zr_boot_name(g, name)
  k = zr_global(g)
  RClass.set_name(k, zr_str_new(zr_symbol_name_ptr(name), zr_symbol_name_len(name)))
  zr_const_set(zr_global(G_OBJECT), name, k)
end

