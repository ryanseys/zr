# The Unicode case mappings, read off ruby and written as tables the
# runtime maps characters through.
#
#   ruby tool_unicode.rb > rt/core/unicode.rb
KINDS = {
  "UP" => ->(c) { c.upcase },
  "DOWN" => ->(c) { c.downcase },
  "TITLE" => ->(c) { c.capitalize },
  "SWAP" => ->(c) { c.swapcase },
  "FOLD" => ->(c) { c.downcase(:fold) }
}.freeze

single = Hash.new { |h, k| h[k] = {} }
multi = Hash.new { |h, k| h[k] = {} }

(0..0x10FFFF).each do |cp|
  next if (0xD800..0xDFFF).cover?(cp)

  char = begin
    cp.chr(Encoding::UTF_8)
  rescue RangeError
    next
  end
  KINDS.each do |name, map|
    mapped = map.call(char)
    next if mapped == char

    codepoints = mapped.codepoints
    codepoints.size == 1 ? single[name][cp] = codepoints[0] : multi[name][cp] = codepoints
  end
end

# The single-character mappings as runs of one delta, so a table that
# holds 1,500 characters fits in a few hundred rows.
def runs(table)
  table.keys.sort.each_with_object([]) do |cp, out|
    delta = table[cp] - cp
    last = out.last
    if last && last[0] + last[1] == cp && last[2] == delta
      last[1] += 1
    else
      out << [cp, 1, delta]
    end
  end
end

def rows(values, per_line)
  values.each_slice(per_line).map { |slice| "    #{slice.join(', ')}," }.join("\n")
end

puts "# The Unicode case mappings, generated by tool_unicode.rb. Each"
puts "# RUNS table is a flat list of (first codepoint, how many, how far"
puts "# to move) triples; each MULTI table holds the characters that map"
puts "# to more than one."
puts "class String"
KINDS.each_key do |name|
  puts "  #{name}_RUNS = ["
  puts rows(runs(single[name]).flatten, 12)
  puts "  ].freeze"
  puts
  pairs = multi[name].sort.map { |cp, to| "#{cp} => #{to.inspect}" }
  puts "  #{name}_MULTI = {"
  puts pairs.each_slice(3).map { |slice| "    #{slice.join(', ')}," }.join("\n")
  puts "  }.freeze"
  puts
  puts "  private_constant :#{name}_RUNS, :#{name}_MULTI"
  puts
end
puts "  # The tables by the name each case method asks for, and the two"
puts "  # letters Turkish gives their own rules."
puts "  CASE_RUNS = { up: UP_RUNS, down: DOWN_RUNS, title: TITLE_RUNS, swap: SWAP_RUNS, fold: FOLD_RUNS }.freeze"
puts "  CASE_MULTI = { up: UP_MULTI, down: DOWN_MULTI, title: TITLE_MULTI, swap: SWAP_MULTI, fold: FOLD_MULTI }.freeze"
puts "  KERNEL_CASE = { up: 1, down: 2, title: 3 }.freeze"
puts "  TURKIC = { up: { 105 => 304 }, title: { 105 => 304 }, down: { 73 => 305, 304 => 105 }, fold: { 73 => 305, 304 => 105 }, swap: {} }.freeze"
puts
puts "  private_constant :CASE_RUNS, :CASE_MULTI, :KERNEL_CASE, :TURKIC"
puts "end"
