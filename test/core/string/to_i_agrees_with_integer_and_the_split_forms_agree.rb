  seps.each do |s|
    [0, 2, -1].each do |limit|
      r = (s.nil? ? l.split : l.split(s, limit)) rescue $!.class
      print l.inspect, " ", s.inspect, " ", limit, " ", r.inspect, "\n"
    end
  end
end
