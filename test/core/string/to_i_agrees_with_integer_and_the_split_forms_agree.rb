texts = ["12", " 12", "12 ", "+12", "-12", "1_2", "1__2", "_12", "12_", "0x1f", "0b11", "0o17", "017", "0d19", "12abc", "abc", "", "  ", "\t\n12", "12\n", "9" * 25, "-" + "9" * 25, "1e3", "1.5", "٣"]
