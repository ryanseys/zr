# frozen_string_literal: true

require "spec_helper"

describe "OptionParser programs" do
  it "optparse abbreviation resolves" do
    result = zr(<<~'RUBY')
      # The cycle this program builds on purpose, and the census it leaves
      # behind. A cycle alive at exit is not a defect: it is a ring the
      # program never broke, so the census below is recorded as an
      # observation rather than gated on.
      #
      # OptionParser's own graph. A List holds its Switches and every Switch's block closes over the parser. Two parsers here, where optparse_subset.rb builds four.
      # At exit: cycle leak: 72 objects (Array x15, Hash x12, Proc x11, cell x9, OptionParser::OptionMap x8, OptionParser::Switch::NoArgument x5, OptionParser::List x4, OptionParser::Switch::OptionalArgument x4, OptionParser x2, OptionParser::Switch::RequiredArgument x2)
      # OptionParser resolves a unique long-option PREFIX (`--verb` finds
      # `--verbose`) and raises AmbiguousOption when two candidates share it.
      #
      # optparse collects its candidates through `method(:each).to_proc`, so
      # that proc must carry its block. See a_method_to_proc_carries_its_block.rb.
      require "optparse"
      got = nil
      OptionParser.new { |o| o.on("--verbose") { got = :v } }.parse(["--verb"])
      p got
      begin
        o = OptionParser.new do |op|
          op.on("--foobar") { }
          op.on("--foobaz") { }
        end
        o.parse(["--fooba"])
      rescue OptionParser::AmbiguousOption => e
        puts "#{e.class}: #{e.message}"
      end
    RUBY

    _(result).must_answer <<~'OUT'
      :v
      OptionParser::AmbiguousOption: ambiguous option: --fooba
      Did you mean?  foobar
                     foobaz
    OUT
  end

  it "optparse subset" do
    result = zr(<<~'RUBY')
      # The cycle this program builds on purpose, and the census it leaves
      # behind. A cycle alive at exit is not a defect: it is a ring the
      # program never broke, so the census below is recorded as an
      # observation rather than gated on.
      #
      # OptionParser's own graph. A List holds its Switches and every Switch's block closes over the parser.
      # At exit: cycle leak: 149 objects (Array x33, Hash x25, Proc x23, cell x17, OptionParser::OptionMap x16, OptionParser::List x8, OptionParser::Switch::NoArgument x8, OptionParser::Switch::OptionalArgument x8, OptionParser::Switch::RequiredArgument x7, OptionParser x4)
      # The bundled `optparse` package (packages/optparse), exercised against the
      # same program real Ruby's own OptionParser runs -- the .expected here is
      # generated by CRuby with ITS optparse, so any divergence in the subset shows
      # up as a byte diff.
      require "optparse"
      opts = {}
      parser = OptionParser.new do |o|
        o.banner = "Usage: demo [options] FILE"
        o.separator ""
        o.on("-v", "--verbose", "run verbosely") { |x| opts[:verbose] = x }
        o.on("-n", "--name NAME", "the name") { |v| opts[:name] = v }
        o.on("-c", "--count=N", "how many") { |v| opts[:count] = v }
      end
      argv = ["-v", "--name", "matz", "-c", "3", "file.txt", "--", "-notaflag"]
      rest = parser.parse!(argv)
      p rest
      p argv
      p opts[:verbose]
      p opts[:name]
      p opts[:count]
      puts parser.help

      o2 = OptionParser.new { |o| o.on("-a", "all") {}; o.on("-b", "bee") {} }
      a2 = ["-ab", "x"]
      o2.parse!(a2)
      p a2

      begin
        OptionParser.new { |o| o.on("-x", "ex") {} }.parse!(["--nope"])
      rescue OptionParser::InvalidOption => e
        p e.message
        p e.class.ancestors.include?(StandardError)
      end
      begin
        OptionParser.new { |o| o.on("-n", "--name NAME", "n") {} }.parse!(["--name"])
      rescue OptionParser::MissingArgument => e
        p e.message
      end
    RUBY

    _(result).must_answer <<~'OUT'
      ["file.txt", "-notaflag"]
      ["file.txt", "-notaflag"]
      true
      "matz"
      "3"
      Usage: demo [options] FILE
      
          -v, --verbose                    run verbosely
          -n, --name NAME                  the name
          -c, --count=N                    how many
      ["x"]
      "invalid option: --nope"
      true
      "missing argument: --name"
    OUT
  end

  it "require first line" do
    result = zr(<<~'RUBY')
      # The cycle this program builds on purpose, and the census it leaves
      # behind. A cycle alive at exit is not a defect: it is a ring the
      # program never broke, so the census below is recorded as an
      # observation rather than gated on.
      #
      # OptionParser's own graph, reached through the required file. See optparse_subset.rb.gccheck.
      # At exit: cycle leak: 28 objects (Hash x6, OptionParser::OptionMap x4, Proc x4, cell x4, Array x3, OptionParser::List x2, OptionParser::Switch::OptionalArgument x2, OptionParser x1, OptionParser::Switch::NoArgument x1, OptionParser::Switch::RequiredArgument x1)
      # A `require` on the very first line (byte 0) loads its file, also when
      # another `require` follows it. Both requires must load.
      require "optparse"
      require "set"
      o = OptionParser.new
      puts o.class
    RUBY

    _(result).must_answer "OptionParser\n"
  end
end
