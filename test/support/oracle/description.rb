# The three kernel tables a lowering reads, written as the text an eval
# carries instead of the kernel sources. Each OS layer's kernel has its
# own, so the target names which.
#
#   rake gen:description             this host's OS layer
#   rake 'gen:description[wasm32-wasi]'
require "zr/zr"

target = ARGV.empty? ? Zr::Target.default : Zr::Target.fetch(ARGV.first) || abort("no target #{ARGV.first}")
text = Zr::Machine::Description.of(Zr::Zr.runtime(target).unit).to_text

puts "# Generated by `rake gen:description` from rt/kernel. Do not edit."
puts "module Zr"
puts "  module Machine"
puts "    class Description"
puts "      KERNEL = <<~ROWS"
text.each_line { |line| puts "        #{line}" }
puts "      ROWS"
puts "    end"
puts "  end"
puts "end"
