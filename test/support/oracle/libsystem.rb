# frozen_string_literal: true

# The libSystem names ze0 imports, as the list `Obj::MachO::Executable` reads: every
# `Machine.import` and `Machine.extern` in darwin's kernel and test/zr, and
# every callee the native fixtures make, that this host's libSystem defines. With the list
# committed, whether `Obj::MachO::Executable` can link a unit answers the same on
# every host.
#
#   rake gen:libsystem
require "fiddle"
require "ze0/native/build"
require "ze0/zr"
require_relative "../../native/fixtures"

root = File.expand_path("../../..", __dir__)
kernel = Ze0::Zr.kernel_files(Ze0::Target::AARCH64_DARWIN)
names = (kernel + Dir[File.join(root, "test/zr/**/*.rb")].sort).flat_map do |file|
  File.read(file).scan(/Machine\.import\s+"([^"]+)"|Machine\.extern\(:(\w+)\)/).flatten.compact
end
names += Ze0::Native::Fixtures::NAMES.flat_map do |name|
  functions, data = Ze0::Native::Fixtures.build(name)
  Ze0::Native::Build.unit(functions, data).imports
end

libsystem = Fiddle::Handle.new(Ze0::Obj::MachO::Executable::LIBSYSTEM)
found = names.uniq.sort.select do |name|
  libsystem[name]
  true
rescue Fiddle::DLError
  false
end

puts "# frozen_string_literal: true"
puts
puts "# Generated by `rake gen:libsystem` from rt/kernel, test/zr and the native"
puts "# fixtures. Do not edit."
puts "module Ze0"
puts "  module Obj"
puts "    module MachO"
puts "      class Executable"
puts "        # The names ze0 imports that libSystem defines."
puts "        LIBSYSTEM_NAMES = %w["
found.each { |name| puts "          #{name}" }
puts "        ].freeze"
puts "      end"
puts "    end"
puts "  end"
puts "end"
