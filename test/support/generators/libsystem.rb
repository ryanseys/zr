# frozen_string_literal: true

# Writes the list of libSystem names that zr imports, which
# `Obj::MachO::Executable` reads. The list contains each `Machine.import` and
# `Machine.extern` in darwin's kernel and test/machine, and each callee of the
# native fixtures, that this host's libSystem defines. The list is committed,
# so `Obj::MachO::Executable` gives the same link result on every host.
#
#   rake gen:libsystem
require "fiddle"
require "zr/native/build"
require "zr/runtime"
require_relative "../../native/fixtures"

root = File.expand_path("../../..", __dir__)
kernel = Zr.kernel_files(Zr::Target::AARCH64_DARWIN)
names = (kernel + Dir[File.join(root, "test/machine/**/*.rb")].sort).flat_map do |file|
  File.read(file).scan(/Machine\.import\s+"([^"]+)"|Machine\.extern\(:(\w+)\)/).flatten.compact
end
names += Zr::Native::Fixtures::NAMES.flat_map do |name|
  functions, data = Zr::Native::Fixtures.build(name)
  Zr::Native::Build.unit(functions, data).imports
end

libsystem = Fiddle::Handle.new(Zr::Obj::MachO::Executable::LIBSYSTEM)
found = names.uniq.sort.select do |name|
  libsystem[name]
  true
rescue Fiddle::DLError
  false
end

puts "# frozen_string_literal: true"
puts
puts "# Generated by `rake gen:libsystem` from runtime/kernel, test/machine and the native"
puts "# fixtures. Do not edit."
puts "module Zr"
puts "  module Obj"
puts "    module MachO"
puts "      class Executable"
puts "        # The names zr imports that libSystem defines."
puts "        LIBSYSTEM_NAMES = %w["
found.each { |name| puts "          #{name}" }
puts "        ].freeze"
puts "      end"
puts "    end"
puts "  end"
puts "end"
