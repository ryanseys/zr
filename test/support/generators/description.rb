# Writes the three kernel tables that a lowering reads, as text. Eval
# support includes this text in place of the kernel sources. The kernel
# of each OS layer has its own tables, so the target selects the layer.
#
#   rake gen:description             this host's OS layer
#   rake 'gen:description[wasm32-wasi]'
require "zr/runtime"

target = ARGV.empty? ? Zr::Target.default : Zr::Target.fetch(ARGV.first) || abort("no target #{ARGV.first}")
text = Zr::Machine::Description.of(Zr.runtime(target).unit).to_text

puts "# Generated by `rake gen:description` from runtime/kernel. Do not edit."
puts "module Zr"
puts "  module Machine"
puts "    class Description"
puts "      KERNEL = <<~ROWS"
text.each_line { |line| puts "        #{line}" }
puts "      ROWS"
puts "    end"
puts "  end"
puts "end"
