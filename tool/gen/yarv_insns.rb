# frozen_string_literal: true

require_relative "../gen"

module Zr
  module Dev
    module Commands
      class Gen
        # Reads the names of the pinned ruby's YARV instructions, and writes
        # them as data. zr compiles to machine code and has no instructions,
        # but RubyVM::INSTRUCTION_NAMES lists ruby's.
        class YarvInsns < Generator
          host_ruby!
          writes "lib/zr/runtime/core/yarv_insns.rb"

          def write(io)
            rows = RubyVM::INSTRUCTION_NAMES.each_slice(6).map { |names| "    #{names.map(&:inspect).join(", ")}," }
            io.puts <<~RUBY
              # frozen_string_literal: true

              # The names of ruby's YARV instructions, generated by `zr-dev gen
              # yarv_insns` from the ruby that .ruby-version pins, in its order.
              class RubyVM
                INSTRUCTION_NAMES = [
              #{rows.join("\n")}
                ].freeze
              end
            RUBY
          end
        end
      end
    end
  end
end
