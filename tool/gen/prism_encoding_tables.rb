# frozen_string_literal: true

require_relative "../gen"

module Zr
  module Dev
    module Commands
      class Gen
        # Writes lib/zr/runtime/ext/prism/ruby/encoding_tables.rb from the bundled
        # prism's src/encoding.c and include/prism/internal/encoding.h
        # (`Dev.prism`). The file
        # contains the Unicode code point ranges, the byte tables, the UTF-8
        # decoder's state table, each encoding's name and functions in
        # pm_encoding_t order, and the names that pm_encoding_find accepts.
        class PrismEncodingTables < Generator
          writes "lib/zr/runtime/ext/prism/ruby/encoding_tables.rb"

          def c_source(path) = Dev.prism(path)

          def numbers(text) = text.scan(/0x\h+|\d+/).map { |n| Integer(n) }

          # The numbers of `static const T name[...] = { ... };`.
          def array(source, name)
            body = source[/\b#{name}\[[^\]]*\]\s*=\s*\{(.*?)\};/m, 1] or raise "no #{name}"
            numbers(body.gsub(%r{//[^\n]*}, ""))
          end

          def bytes_literal(values)
            raise "a byte table has #{values.size} entries" unless values.size == 256

            values.pack("C*").unpack1("H*").scan(/../).each_slice(16).map { |row| "      \"#{row.map { |h| "\\x#{h}" }.join}\"" }.join(" \\\n")
          end

          # Byte tables, one after another, as one literal.
          def tables_literal(tables) = tables.map { |table| bytes_literal(table) }.join(" \\\n")

          def ranges_literal(values)
            values.each_slice(2).map { |low, high| "0x#{low.to_s(16).upcase}, 0x#{high.to_s(16).upcase}" }.each_slice(6).map { |row| "      #{row.join(", ")}," }.join("\n")
          end

          def write(io)
            source = c_source("src/encoding.c")
            header = c_source("include/prism/internal/encoding.h")

            order = header[/typedef enum \{(.*?)\} pm_encoding_type_t;/m, 1].scan(/PM_ENCODING_(\w+)/).flatten - %w[MAXIMUM]
            rows = source[/^const pm_encoding_t pm_encodings\[\] = \{(.*?)^\};/m, 1]
              .scan(/\[PM_ENCODING_(\w+)\]\s*=\s*\{(.*?)\}/m).to_h do |id, body|
                fields = body.scan(/\.(\w+)\s*=\s*("[^"]*"|\w+)/).to_h
                [id, [fields.fetch("name").delete('"'), *%w[char_width alnum_char alpha_char isupper_char].map { |f| fields.fetch(f).delete_prefix("pm_encoding_") }, fields.fetch("multibyte") == "true"]]
              end
            raise "pm_encodings and pm_encoding_type_t disagree" unless rows.keys == order

            tables = source.scan(/^static const uint8_t pm_encoding_(\w+)_table\[256\]/).flatten
                           .to_h { |name| [name, array(source, "pm_encoding_#{name}_table")] }
            ascii = tables.fetch("ascii")
            # Many tables hold ASCII's bytes or another table's; each
            # distinct one is written once.
            distinct = tables.values.uniq - [ascii]
            names = []
            source[/^pm_encoding_find\(.*?^\}/m].scan(/ENCODING([12])\(((?:"[^"]*",\s*)+)PM_ENCODING_(\w+)\)/) do |_, list, id|
              list.scan(/"([^"]*)"/).flatten.each { |name| names << [name, id] }
            end

            io.print <<~RUBY
              # frozen_string_literal: true
              # shareable_constant_value: literal

              # Generated by `zr-dev gen prism_encoding_tables` from the bundled prism's
              # src/encoding.c. Do not edit.

              module Prism
                module Ruby
                  module Encodings
                    # unicode_alpha_codepoints, unicode_alnum_codepoints and
                    # unicode_isupper_codepoints: inclusive ranges, low then high.
                    UNICODE_ALPHA = [
              #{ranges_literal(array(source, "unicode_alpha_codepoints"))}
                    ]

                    UNICODE_ALNUM = [
              #{ranges_literal(array(source, "unicode_alnum_codepoints"))}
                    ]

                    UNICODE_ISUPPER = [
              #{ranges_literal(array(source, "unicode_isupper_codepoints"))}
                    ]

                    # pm_encoding_unicode_table: bit 0 alphabetic, 1 alphanumeric,
                    # 2 uppercase, for the first 256 code points.
                    UNICODE_TABLE = (
              #{bytes_literal(array(source, "pm_encoding_unicode_table"))}
                    ).b.freeze

                    # pm_utf_8_dfa: 256 byte types, then 16 transitions per state.
                    UTF_8_DFA = #{array(source, "pm_utf_8_dfa").inspect}.freeze

                    # pm_encoding_ascii_table.
                    ASCII_TABLE = (
              #{bytes_literal(ascii)}
                    ).b.freeze

                    # Each other distinct pm_encoding_<name>_table, 256 bytes
                    # apiece, and the index of each name's table. A name whose
                    # table holds ASCII's bytes has none.
                    TABLE_BYTES = (
              #{tables_literal(distinct)}
                    ).b.freeze
                    TABLES = {
              #{tables.filter_map { |name, table| "        #{name.inspect} => #{distinct.index(table)}," unless table == ascii }.join("\n")}
                    }

                    # pm_encodings, in pm_encoding_type_t order: the name, then the
                    # char_width, alnum_char, alpha_char and isupper_char functions
                    # (pm_encoding_ dropped), then whether it is multibyte.
                    ENCODINGS = {
              #{order.map { |id| "        #{id.to_sym.inspect} => #{rows.fetch(id).inspect}," }.join("\n")}
                    }

                    # pm_encoding_find's names, compared without case, in its order.
                    NAMES = [
              #{names.map { |name, id| "        [#{name.inspect}, #{id.to_sym.inspect}]," }.join("\n")}
                    ]
                  end
                end
              end
            RUBY
          end
        end
      end
    end
  end
end
