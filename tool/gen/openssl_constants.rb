# frozen_string_literal: true

require_relative "../gen"
require "openssl"

module Zr
  module Dev
    class Gen
      # Every Integer constant ruby's openssl extension defines in C,
      # with the value ruby answers, in the order ruby defined them. The
      # values are the OpenSSL 3 headers' macros, which the port cannot
      # read, so ruby, the oracle, gives them.
      #
      #   zr-dev gen openssl_constants
      #
      # "The order ruby defined them" is stable across runs on one
      # build of the gem (the C extension walks its own constant table
      # the same way every time), but not guaranteed across builds: a
      # different OpenSSL the gem links against can order its own
      # `rb_define_const` calls differently. On this checkout, the
      # generator's 264 names and values match runtime/ext/openssl/
      # ossl/constants.rb exactly, in a different order. `--check` may
      # report the file out of date for that reason alone; read the
      # diff before blessing it, since a real change reorders lines
      # anyway.
      class OpensslConstants < Generator
        host_ruby!
        writes "runtime/ext/openssl/ossl/constants.rb"

        def write(io)
          rows = []
          walk = lambda do |mod, seen|
            next if seen[mod]

            seen[mod] = true
            mod.constants(false).each do |name|
              value = mod.const_get(name)
              if value.is_a?(Module)
                walk.(value, seen) if value.name == "#{mod.name}::#{name}"
              elsif value.is_a?(Integer) && mod.const_source_location(name)&.first.to_s.end_with?(".bundle", ".so")
                rows << [mod.name, name, value] unless mod == OpenSSL && name == :OPENSSL_VERSION_NUMBER
              end
            end
          end
          walk.(OpenSSL, {})

          io.puts "# frozen_string_literal: true"
          io.puts
          io.puts "# Generated by `zr-dev gen openssl_constants` from ruby #{RUBY_VERSION}'s openssl"
          io.puts "# #{OpenSSL::VERSION}. Do not edit."
          io.puts "module OpenSSL"
          rows.chunk { |mod, _, _| mod }.each_with_index do |(mod, group), i|
            io.puts unless i.zero?
            scope = mod.delete_prefix("OpenSSL").delete_prefix("::")
            group.each do |_, name, value|
              text = value.negative? || value < 0x10000 ? value.to_s : format("0x%x", value)
              io.puts "  #{scope.empty? ? "" : "#{scope}::"}#{name} = #{text}"
            end
          end
          io.puts "end"
        end
      end
    end
  end
end
