# frozen_string_literal: true

require_relative "../gen"

module Zr
  module Dev
    module Commands
      class Gen
        # Writes the list of libSystem names that zr imports, which
        # `Obj::MachO::Executable` reads. The list contains each import
        # (`def self.name(...) = Machine.import`) and `Machine.extern` in
        # darwin's kernel and test/machine, and each callee of the native
        # fixtures, that this host's libSystem defines. The list is committed, so
        # `Obj::MachO::Executable` gives the same link result on every host.
        # `test/unit/libsystem_test.rb` fails when it is out of date.
        class Libsystem < Generator
          writes "lib/zr/obj/macho/libsystem.rb"

          def write(io)
            require "fiddle"
            require_relative "../../lib/zr/native/build"
            require_relative "../../lib/zr/runtime"
            require_relative "../../test/native/fixtures"

            kernel = Zr::RuntimeSources.for(Target::AARCH64_DARWIN).kernel_files
            names = (kernel + Dir[Dev.path("test/machine/**/*.rb")].sort).flat_map do |file|
              File.read(file).scan(/def self\.(\w+)\b.*= Machine\.import\b|Machine\.extern\(:(\w+)\)/).flatten.compact
            end
            names += Native::Fixtures::NAMES.flat_map do |name|
              functions, data = Native::Fixtures.build(name)
              Native::Build.unit(functions, data).imports
            end

            libsystem = Fiddle::Handle.new(Obj::MachO::Executable::LIBSYSTEM)
            found = names.uniq.sort.select do |name|
              libsystem[name]
              true
            rescue Fiddle::DLError
              false
            end

            io.puts "# frozen_string_literal: true"
            io.puts
            io.puts "# Generated by `zr-dev gen libsystem` from lib/zr/runtime/kernel, test/machine and the native"
            io.puts "# fixtures. Do not edit."
            io.puts "module Zr"
            io.puts "  module Obj"
            io.puts "    module MachO"
            io.puts "      class Executable"
            io.puts "        # The names zr imports that libSystem defines."
            io.puts "        LIBSYSTEM_NAMES = %w["
            found.each { |name| io.puts "          #{name}" }
            io.puts "        ].freeze"
            io.puts "      end"
            io.puts "    end"
            io.puts "  end"
            io.puts "end"
          end
        end
      end
    end
  end
end
