# frozen_string_literal: true

require_relative "../gen"

module Zr
  module Dev
    module Commands
      class Gen
        # Which of ruby's own methods warn when a program redefines them,
        # and the line that the warning names. rb_method_entry_make warns
        # for most of them, but not for one that another name shares (an
        # alias, such as Enumerable#map), and it names the def of a method
        # written in `<internal:*>`. The generator redefines each method of
        # each core class in a child ruby of its own, under $VERBOSE, and
        # reads what the child writes to standard error.
        #
        # The table is text that a hidden method returns, so the core makes
        # no String of it at boot; Warning.redefinitions reads it on first
        # use. Each line is an owner, `Owner#` for its instance methods or
        # `Owner.` for its singleton methods, then its methods: a bare name
        # warns and names no line, `name,-` does not warn, and
        # `name,<internal:file>:line` names the previous definition.
        class Redefinitions < Generator
          host_ruby!
          writes "lib/zr/runtime/core/redefinitions.rb"

          # rb_method_entry_make's own warnings about Object, which the
          # kernel writes whatever the table says.
          OTHER = /may cause (?:infinite loop|serious problems)/

          # A child is a plain ruby, even under `bundle exec`.
          PLAIN = { "RUBYOPT" => nil, "RUBYLIB" => nil, "BUNDLE_GEMFILE" => nil }.freeze

          # The longest line of the table, before a line for the same owner
          # goes on.
          WIDTH = 100

          def write(io)
            io.print <<~RUBY
              # frozen_string_literal: true

              # Generated by `zr-dev gen redefinitions` from the pinned ruby. Do not edit.
              #
              # Whether each method of ruby's core warns when a program redefines it,
              # and the <internal:*> line that the warning names, if any. Each line is
              # an owner, `Owner#` for its instance methods or `Owner.` for its
              # singleton methods, then its methods: a bare name warns and names no
              # line, `name,-` does not warn, and `name,<line>` names the previous
              # definition. Warning.redefinitions reads it on first use.
              module Warning
                def self.redefinition_rows
                  Primitive.attr! :hidden
                  <<~ROWS
              #{lines(rows_of(methods)).map { |line| "      #{line}\n" }.join}      ROWS
                end
              end
            RUBY
          end

          private

          # The table's lines: each owner's tokens, in order, no wider than
          # WIDTH unless one token is.
          def lines(rows)
            by_owner = rows.sort_by(&:first).group_by { |key, _| key[/\A[\w:]+[#.]/] || raise("no owner in #{key}") }
            by_owner.flat_map do |owner, entries|
              tokens = entries.map { |key, where| token(key.delete_prefix(owner), where) }
              tokens.each_with_object([+owner]) do |token, out|
                out << +owner if out.last.size + 1 + token.size > WIDTH && out.last.size > owner.size
                out.last << " " << token
              end
            end
          end

          #: (String name, (String | false)? where) -> String
          def token(name, where)
            raise "a method name with a space or a comma: #{name.inspect}" if name.match?(/[ ,]/)

            case where
            when nil then name
            when false then "#{name},-"
            else "#{name},#{where}"
            end
          end

          # Every method that a core class or module defines itself, as a
          # ruby with no gems has them.
          def methods
            script = <<~'RUBY'
              seen = {}
              walk = lambda do |mod|
                next if seen[mod]

                seen[mod] = true
                mod.constants(false).each do |name|
                  next if mod.autoload?(name)

                  value = mod.const_get(name, false)
                  walk.(value) if value.is_a?(Module) && value.name == "#{mod.name == "Object" ? "" : "#{mod.name}::"}#{name}"
                end
              end
              walk.(Object)
              seen.each_key do |mod|
                own = mod.public_instance_methods(false) + mod.protected_instance_methods(false) + mod.private_instance_methods(false)
                own.each { |name| puts [mod.name, 0, name].join("\t") }
                single = mod.singleton_class
                (single.public_instance_methods(false) + single.private_instance_methods(false)).each { |name| puts [mod.name, 1, name].join("\t") }
              end
            RUBY
            IO.popen(PLAIN, [RbConfig.ruby, "--disable-gems", "-e", script], &:read).lines.map do |line|
              owner, singleton, name = line.chomp.split("\t", 3)
              [owner, singleton == "1", name]
            end
          end

          # Each child runs by itself; six at a time keep the run short
          # without crowding the machine.
          def rows_of(list) = Dev.parallel_map(list, jobs: 6) { |item| row(*item) }

          # The warning that redefining one method writes, in a child that
          # keeps the damage to itself.
          def row(owner, singleton, name)
            script = <<~'RUBY'
              owner, singleton, name = ARGV
              target = Object.const_get(owner)
              target = target.singleton_class if singleton == "1"
              $VERBOSE = true
              target.send(:define_method, name.to_sym) { |*| nil }
            RUBY
            text = IO.popen(PLAIN, [RbConfig.ruby, "--disable-gems", "-e", script, owner, singleton ? "1" : "0", name], err: %i[child out], &:read)
            lines = text.lines.grep_v(OTHER)
            key = "#{owner}#{singleton ? "." : "#"}#{name}"
            return [key, false] unless lines.any? { |line| line.include?("method redefined; discarding old") }

            previous = lines.find { |line| line.include?("previous definition of") }
            [key, previous && previous[/\A(<internal:[^>]+>:\d+):/, 1]]
          end
        end
      end
    end
  end
end
