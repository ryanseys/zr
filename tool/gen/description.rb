# frozen_string_literal: true

require_relative "../gen"

module Zr
  module Dev
    class Gen
      # Writes the three kernel tables that a lowering reads, as text. Eval
      # support includes this text in place of the kernel sources. The
      # kernel of each OS layer has its own tables, so the target selects
      # the layer. `test/unit/description_test.rb` fails when a file is
      # out of date.
      #
      #   zr-dev gen description                       every OS layer
      #   zr-dev gen description --target wasm32-wasi  one layer
      class Description < Generator
        usage "[--target TRIPLE] [--check]"

        def options(o)
          super
          o.on("--target TRIPLE", "the target whose OS layer to write (default: every layer)") { |v| @triple = v }
        end

        def run(_argv)
          require_relative "../../lib/zr/runtime"
          targets.map do |target|
            Dev.write("runtime/ext/os/#{target.os_layer}/zr_description.rb", check: check?) { |io| write(io, target) }
          end.all?
        end

        # One target for each OS layer, or the one that --target names.
        def targets
          return Target.all.select { |target| target.os_layer == target.os.to_s }.uniq(&:os_layer) unless @triple

          [Target.fetch(@triple) || fail!("no target #{@triple}; `zr targets` names them")]
        end

        def write(io, target)
          text = Machine::Description.of(Zr.runtime(target).unit).to_text
          io.puts "# Generated by `zr-dev gen description` from runtime/kernel. Do not edit."
          io.puts "module Zr"
          io.puts "  module Machine"
          io.puts "    class Description"
          io.puts "      KERNEL = <<~ROWS"
          text.each_line { |line| io.puts "        #{line}" }
          io.puts "      ROWS"
          io.puts "    end"
          io.puts "  end"
          io.puts "end"
        end
      end
    end
  end
end
