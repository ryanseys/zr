# frozen_string_literal: true

require_relative "../gen"

module Zr
  module Dev
    class Gen
      # Writes sig/zr_kern.rbs: the type of each def in the kernel, from its
      # `sig`, as Ruby sees it (A6). I8, I32, Word, Ptr and Value are
      # Integers, Bool is bool and F64 is Float. A def that the OS or arch
      # layers give is in the file once, from the first target that has it;
      # each layer gives the same signature.
      class KernRbs < Generator
        writes "sig/zr_kern.rbs"

        TARGETS = %w[aarch64-apple-darwin aarch64-linux-musl wasm32-wasi].freeze
        RBS = { "Word" => "Integer", "I32" => "Integer", "I8" => "Integer", "Ptr" => "Integer", "Value" => "Integer",
                "Bool" => "bool", "F64" => "Float", "Void" => "void" }.freeze

        def write(io)
          require_relative "../../lib/zr/runtime"

          defs = {}
          TARGETS.each do |triple|
            files = RuntimeSources.for(Target.fetch(triple)).kernel_files
            unit = Machine::Lower.new(files.map { |path| [File.read(path), path] }, Machine::Symbols.new).tap(&:run)
            unit.declared_defs.each_value { |d| defs[d.name] ||= d }
          end

          io.puts "# Generated by `zr-dev gen kern_rbs` from lib/zr/runtime/kernel. Do not edit."
          io.puts "module Zr"
          io.puts "  module Kern"
          defs.keys.sort.each do |name|
            d = defs.fetch(name)
            params = d.params.map { |param, type| "#{RBS.fetch(type, "Integer")} #{param}" }
            io.puts "    def #{name}: (#{params.join(", ")}) -> #{RBS.fetch(d.ret, "Integer")}"
          end
          io.puts "  end"
          io.puts "end"
        end
      end
    end
  end
end
