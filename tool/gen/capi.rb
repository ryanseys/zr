# frozen_string_literal: true

require_relative "../gen"
require_relative "../../lib/zr/prism"

module Zr
  module Dev
    module Commands
      class Gen
        # docs/reference/c-api.md: the functions and the data of ruby's C API
        # that zr's kernel gives a C extension, read from the kernel's C API
        # files (lib/zr/runtime/kernel/capi/*.rb), one section for each file.
        # The names are the ones that a build checks an extension's imports
        # against (`Ext::CApi.names`).
        class CApi < Generator
          writes "docs/reference/c-api.md"

          DIR = "lib/zr/runtime/kernel/capi"

          def write(io)
            require_relative "../../lib/zr/ext/c_api"
            files = Dir[File.join(Paths::ROOT, DIR, "*.rb")].sort.map { |path| [path, names_in(path)] }.reject { |_, names| names.empty? }
            total = files.sum { |_, names| names.size }
            io.print(<<~MD)
              <!-- Generated by `zr-dev gen capi`. Do not edit. -->
              # The C API

              A C extension that zr runs (`--native-ext`, see
              [How to use a C extension](../how-to/use-a-c-extension.md))
              calls ruby 4.0's C API. zr's kernel gives #{total} of its
              functions and data words, each one a def or a word of kernel
              Ruby named after its C symbol, under `#{DIR}/`. This page lists
              them, one section for each file.

              A build checks the names that an extension imports against this
              list. A name that is not here stops the build with exit status 3
              and the name, before anything runs:

              ```
              zr: foo.bundle: zr's C API has no rb_foo yet (`zr-dev ext imports foo.bundle` lists what it uses)
              ```

              A C TracePoint (`rb_tracepoint_new`) is a Ruby TracePoint whose
              hook is a C function, and its trace arg answers as the
              TracePoint's methods do. An extension that hooks trace events
              makes zr build the program with them, as a program that names
              TracePoint does. The debug inspector (`rb_debug_inspector_*`)
              gives the frames that a backtrace shows, from the innermost
              outward. A frame's depth counts the frames from it outward, so
              two depths compare as ruby's do, but the number is not ruby's.
              An event hook (`rb_add_event_hook`) is a C TracePoint too, and
              a C TracePoint hears the internal events NEWOBJ and FREEOBJ.
              A frame of `rb_profile_frames` is the address of its code, no
              Fixnum, as ruby's is a pointer: a signal handler can take one,
              as stackprof's does, `rb_gc_mark` of it does nothing, and a
              postponed job (`rb_postponed_job_*`) runs at the
              next safe point. The private `rb_iseq_*` and `rb_iseqw_*` that
              debug and datadog-ci declare take the address of the code's
              FrameMeta for an `rb_iseq_t *`; `rb_iseq_code_location` gives
              lines and no columns (both are 0). A walk of the heap finds no
              instruction sequences, as zr's code is not objects.

            MD
            files.each do |path, names|
              io.print(<<~MD)
                ## #{File.basename(path, ".rb")}

                #{summary_of(path)}

                #{names.map { |name| "`#{name}`" }.join(", ")}

              MD
            end
          end

          private

          # The C names that the file gives, in the order it gives them.
          def names_in(path)
            found = Set.new
            Zr::Ext::CApi.collect(Prism.parse_file(path).value, found)
            found.to_a
          end

          # The first sentence of the comment that opens the file's module.
          def summary_of(path)
            comment = File.read(path).lines.drop(1).take_while { |line| line.start_with?("  #") }
            text = comment.map { |line| line.delete_prefix("  #").strip }.join(" ").strip
            text[/\A.*?\.(?=\s|\z)/m] || text
          end
        end
      end
    end
  end
end
