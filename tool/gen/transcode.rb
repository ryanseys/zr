# frozen_string_literal: true

require_relative "../gen"

module Zr
  module Dev
    module Commands
      class Gen
        # Reads the byte tables of the single-byte encodings from ruby. In all
        # of them, a byte below 128 represents itself. Thus a row contains only
        # bytes 128 to 255: four hex digits for the code point of each byte, or
        # `----` when the encoding does not define the byte.
        class Transcode < Generator
          host_ruby!
          writes "lib/zr/runtime/core/transcode.rb"

          UNMAPPED = "\u{1F600}"

          # Reads how ruby writes a conversion error for each encoding: the name
          # of its converter, and whether a one-step conversion shows as
          # `X from A to B` or as a chain. This method causes an error to read
          # both. Returns nil when the encoding has no converter.
          def shape(encoding)
            message = conversion_message { UNMAPPED.encode(encoding) }
            return nil if message.start_with?("code converter not found")

            short = !message.include?(" in conversion from ")
            # The name that the transcoder declares, which the converter shows
            # (WINDOWS-1252 for Windows-1252).
            step = short ? message[/ from UTF-8 to (\S+)\z/, 1] : message[/\AU\+\h+ to (.*?) in conversion from /, 1]
            [short, step, short_from?(encoding)]
          end

          # The same test for the other direction. It uses a byte that the
          # encoding does not define. An encoding that defines all bytes never
          # raises here, so the result does not matter (it returns true).
          def short_from?(encoding)
            byte = (128..255).find { |b| converted { [b].pack("C").force_encoding(encoding).encode("UTF-8") }.nil? }
            return true if byte.nil?

            message = conversion_message { [byte].pack("C").force_encoding(encoding).encode("UTF-8") }
            !message.include?(" in conversion from ")
          end

          def write(io)
            pairs = (0..255).flat_map { |a| (0..255).map { |b| [a, b].pack("CC") } }

            single = Encoding.list.reject(&:dummy?).select do |encoding|
              pairs.none? { |text| converted { text.force_encoding(encoding).length == 1 } }
            end

            rows = single.filter_map do |encoding|
              next if encoding == Encoding::BINARY || encoding == Encoding::US_ASCII

              points = (128..255).map do |byte|
                code = converted { [byte].pack("C").force_encoding(encoding).encode("UTF-8").ord }
                code ? format("%04X", code) : "----"
              end
              "  #{encoding.name.inspect} => #{points.join.inspect},"
            end

            # Whether the encoding changes the case of its non-ASCII characters.
            # Those that do use the Unicode rules for their code points. The
            # others change the case of ASCII characters only.
            cased = single.select do |encoding|
              next false if encoding == Encoding::BINARY || encoding == Encoding::US_ASCII

              (128..255).any? { |byte| [byte].pack("C").force_encoding(encoding).upcase.bytes != [byte] }
            end

            shapes = single.filter_map do |encoding|
              row = shape(encoding)
              next "  #{encoding.name.inspect} => nil," if row.nil?

              "  #{encoding.name.inspect} => [#{row[0]}, #{row[1].inspect}, #{row[2]}],"
            end

            io.puts "# frozen_string_literal: true"
            io.puts
            io.puts <<~HEADER
              # Derived from CRuby's enc/trans tables (Ruby or BSD-2-Clause, and the
              # mapping data's own notices); see THIRD_PARTY_NOTICES.md.
              #
              # The single-byte encodings' tables, generated by `zr-dev gen transcode`.
              # A row holds bytes 128 to 255: four hex digits for the code point the
              # byte reads as, `----` where the encoding leaves the byte out. Bytes
              # below 128 stand for themselves in every one of these encodings.
              class Encoding
                HIGH = {
              #{rows.join("\n").gsub(/^/, "  ")}
                }.freeze
                private_constant :HIGH

                # How a conversion error reads: whether a one-step conversion to
                # this encoding words as `X from A to B` rather than as a chain,
                # the name the converter answers to, and the same short-form
                # question for a conversion away from it. A nil row is an encoding
                # with no converter at all.
                SHAPES = {
              #{shapes.join("\n").gsub(/^/, "  ")}
                }.freeze
                private_constant :SHAPES

                # The encodings that case their non-ASCII characters, which they do
                # as Unicode does. Every other single-byte encoding folds the ASCII
                # half alone.
                CASED = [
              #{cased.map { |e| "  #{e.name.inspect}," }.join("\n").gsub(/^/, "  ")}
                ].freeze
                private_constant :CASED
              end
            HEADER
          end
        end
      end
    end
  end
end
