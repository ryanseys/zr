# frozen_string_literal: true

require_relative "../gen"

module Zr
  module Dev
    class Gen
      # Reads the encoding registry from ruby, and writes it as a table. The
      # runtime makes its Encoding objects from this table.
      class Encodings < Generator
        host_ruby!
        writes "runtime/core/encodings.rb"

        def write(io)
          # Before any code uses an encoding, `inspect` shows if its table is
          # already loaded. A new program starts in this state.
          loaded = Encoding.list.to_h { |encoding| [encoding.name, !encoding.inspect.include?("(autoload)")] }

          # Whether one byte is always one character: no pair of bytes in the
          # encoding makes a single character.
          pairs = (0..255).flat_map { |a| (0..255).map { |b| [a, b].pack("CC") } }
          bytewise = Encoding.list.to_h do |encoding|
            [encoding.name, pairs.none? { |text| (text.force_encoding(encoding).length == 1 rescue false) }]
          end

          rows = Encoding.list.map do |encoding|
            names = encoding.names.map(&:inspect).join(", ")
            "  [[#{names}], #{encoding.dummy?}, #{encoding.ascii_compatible?}, " \
              "#{loaded[encoding.name]}, #{bytewise[encoding.name]}],"
          end

          # The constants, in the order that ruby defines them, each with the
          # name of its encoding.
          constants = Encoding.constants.filter_map do |const|
            value = Encoding.const_get(const)
            next unless value.is_a?(Encoding)

            "  [#{const.to_s.inspect}, #{value.name.inspect}],"
          end

          io.puts "# frozen_string_literal: true"
          io.puts
          io.puts <<~HEADER
            # The encodings ruby knows, generated by `zr-dev gen encodings`, in
            # ruby's own index order. A row is the canonical name with its
            # aliases, whether the encoding is a dummy one, whether its bytes
            # below 128 are ASCII, whether a fresh program has its table
            # already, and whether one byte is always one character. The second
            # table is the constant each encoding answers to.
            class Encoding
              UNICODE_VERSION = #{Encoding::UNICODE_VERSION.inspect}

              ROWS = [
            #{rows.join("\n").gsub(/^/, "  ")}
              ].freeze
              private_constant :ROWS

              CONSTANTS = [
            #{constants.join("\n").gsub(/^/, "  ")}
              ].freeze
              private_constant :CONSTANTS
            end
          HEADER
        end
      end
    end
  end
end
