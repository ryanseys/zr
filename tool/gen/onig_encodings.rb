# frozen_string_literal: true

require_relative "../gen"

module Zr
  module Dev
    class Gen
      # The tables of Onigmo's encodings past UTF-8, checked against the
      # ruby the .ruby-version pins and written as the tables the
      # runtime's Regexp engine reads
      # (lib/zr/runtime/core/regexp/onig/encoding_tables.rb).
      #
      #   zr-dev gen onig_encodings
      #
      # The tables come from CRuby's own encoding sources, read at
      # development time and never vendored: each single-byte encoding's
      # ctype bits, lower-case table and case fold pairs
      # (enc/iso_8859_*.c, koi8_*.c, windows_*.c), each multibyte
      # encoding's lead-byte lengths, state tables and trail-byte tables
      # (enc/euc_jp.c, shift_jis.h, big5.c, ...), the JIS property
      # ranges, and which encoding each of ruby's replicates reads with.
      # What ruby itself can say is then held to it: every ctype bit to a
      # POSIX bracket over every byte, every character length to
      # String#valid_encoding? over every one- and two-byte sequence,
      # every fold pair to a case-insensitive match. A table ruby
      # disagrees with stops the run.
      class OnigEncodings < Generator
        host_ruby!
        writes "lib/zr/runtime/core/regexp/onig/encoding_tables.rb"

        # Every single-byte encoding this generator reads, in the order
        # SINGLE_BYTE lists them.
        SINGLE_BYTE_FILES = %w[iso_8859_1 iso_8859_2 iso_8859_3 iso_8859_4 iso_8859_5 iso_8859_6 iso_8859_7 iso_8859_8
                                iso_8859_9 iso_8859_10 iso_8859_11 iso_8859_13 iso_8859_14 iso_8859_15 iso_8859_16
                                koi8_r koi8_u windows_1250 windows_1251 windows_1252 windows_1253 windows_1254
                                windows_1257].freeze

        # The states each multibyte encoding's trans table has.
        MULTIBYTE_STATES = { "EUC-JP" => 3, "Shift_JIS" => 2, "Big5" => 3, "GBK" => 2, "CP949" => 2, "EUC-KR" => 2,
                             "EUC-TW" => 4, "GB18030" => 4, "Emacs-Mule" => 7, "CESU-8" => 8 }.freeze

        CTYPE_NAMES = { 1 => "alpha", 2 => "blank", 3 => "cntrl", 4 => "digit", 5 => "graph", 6 => "lower", 7 => "print",
                        8 => "punct", 9 => "space", 10 => "upper", 11 => "xdigit", 12 => "word", 13 => "alnum", 14 => "ascii" }.freeze

        def write(io)
          single = single_byte_tables
          multi = multibyte_tables
          bases = base_encodings(single, multi)
          hold_single_to_ruby(single)
          hold_multibyte_to_ruby(multi)

          io.print(<<~HEAD)
            # Generated by `zr-dev gen onig_encodings` from CRuby #{RUBY}'s enc/*.c.
            # Do not edit.
            #
            # The tables of Onigmo's encodings past UTF-8 (lib/zr/runtime/core/regexp/onig/
            # encoding.rb reads them): ctype bits as 256 little-endian 16-bit
            # words, byte tables as 256 bytes, state tables as 256 signed bytes a
            # state (-1 accepts, -2 fails), fold pairs as (from, to) bytes or
            # 32-bit words, code ranges as a count then (low, high) 32-bit words.
            # Derived from Onigmo; the license is in lib/zr/runtime/core/regexp/onig.rb.
            class Regexp
              module Onig
                module EncTables
                  ASCII_CTYPE = #{u16(ascii_ctype)}.freeze

          HEAD
          io.print "      # [ctype, lower or nil, fold (:ascii, :map, :iso_8859_1), sharp_s, (from, to) pairs or nil, ess-tsett]\n"
          io.print "      SINGLE_BYTE = {\n"
          single.each do |name, e|
            io.print "        #{name.inspect} => [\n"
            io.print "          #{u16(e[:ctype])}.freeze,\n"
            io.print "          #{e[:lower] ? "#{u8(e[:lower])}.freeze" : "nil"},\n"
            io.print "          :#{e[:fold]}, #{e[:sharp_s] ? true : false}, #{e[:map] ? "#{pairs8(e[:map])}.freeze" : "nil"}, #{e[:ess] || 0},\n"
            io.print "        ].freeze,\n"
          end
          io.print "      }.freeze\n\n"

          io.print "      # [EncLen, trans, CAN_BE_TRAIL or nil] of each multibyte encoding.\n"
          io.print "      EUC_JP = [#{u8(multi["EUC-JP"][:len])}.freeze, #{state_table(multi["EUC-JP"][:trans])}.freeze, nil].freeze\n"
          io.print "      SHIFT_JIS = [#{u8(multi["Shift_JIS"][:len])}.freeze, #{state_table(multi["Shift_JIS"][:trans])}.freeze, #{u8(multi["Shift_JIS"][:trail])}.freeze].freeze\n"
          io.print "      BIG5 = [#{u8(multi["Big5"][:len])}.freeze, #{state_table(multi["Big5"][:trans])}.freeze, #{u8(multi["Big5"][:trail])}.freeze].freeze\n"
          io.print "      GBK = [#{u8(multi["GBK"][:len])}.freeze, #{state_table(multi["GBK"][:trans])}.freeze, #{u8(multi["GBK"][:trail])}.freeze].freeze\n"
          io.print "      CP949 = [#{u8(multi["CP949"][:len])}.freeze, #{state_table(multi["CP949"][:trans])}.freeze, #{u8(multi["CP949"][:trail])}.freeze].freeze\n"
          io.print "      EUC_KR = [#{u8(multi["EUC-KR"][:len])}.freeze, #{state_table(multi["EUC-KR"][:trans])}.freeze, nil].freeze\n"
          io.print "      EUC_TW = [#{u8(multi["EUC-TW"][:len])}.freeze, #{state_table(multi["EUC-TW"][:trans])}.freeze, nil].freeze\n"
          io.print "      # GB18030_MAP: C1 0, C2 1, C4 2, CM 3.\n"
          io.print "      GB18030 = [#{u8(multi["GB18030"][:map])}.freeze, #{state_table(multi["GB18030"][:trans])}.freeze, nil].freeze\n"
          io.print "      EMACS_MULE = [#{u8(multi["Emacs-Mule"][:len])}.freeze, #{state_table(multi["Emacs-Mule"][:trans])}.freeze, nil].freeze\n"
          io.print "      CESU_8 = [#{u8(multi["CESU-8"][:len])}.freeze, #{state_table(multi["CESU-8"][:trans])}.freeze, nil].freeze\n\n"

          io.print "      # CaseFoldMap of EUC-JP and Shift_JIS: (from, to) 32-bit words.\n"
          io.print "      EUC_JP_FOLDS = #{u32(multi["EUC-JP"][:map].flatten)}.freeze\n"
          io.print "      SHIFT_JIS_FOLDS = #{u32(multi["Shift_JIS"][:map].flatten)}.freeze\n\n"

          io.print "      # The JIS properties (enc/jis/props.h) in PropertyList order.\n"
          { "EUC_JP_PROPS" => "EUC-JP", "SHIFT_JIS_PROPS" => "Shift_JIS", "WINDOWS_31J_PROPS" => "Windows-31J" }.each do |const, name|
            io.print "      #{const} = [\n"
            multi[name][:props].each_value { |ranges| io.print "        #{u32(ranges)}.freeze,\n" }
            io.print "      ].freeze\n"
          end
          io.print "\n      # Each of ruby's encodings to the Onigmo encoding it reads with.\n"
          io.print "      BASES = {\n"
          bases.each { |name, base| io.print "        #{name.inspect} => #{base.inspect},\n" }
          io.print "      }.freeze\n"
          io.print "    end\n  end\nend\n"
        end

        private

        def source(name) = Dev.cruby("enc/#{name}").gsub(%r{/\*.*?\*/}m, "")

        def enc_files = Dev.cruby_files("enc").grep(/\.[ch]\z/)

        # The body of the C array `name` in `text`, as its tokens.
        def tokens(text, name)
          body = text[/\b#{Regexp.escape(name)}\s*\[[^\]]*\]\s*=\s*\{(.*?)\n\s*\};/m, 1] or fail!("no table #{name}")
          body.scan(/'\\\d{3}'|'[^']'|0x\h+|-?\d+|\b[A-Z]\w*\b/)
        end

        def number(token)
          case token
          when /\A'\\(\d{3})'\z/ then $1.to_i(8)
          when /\A'(.)'\z/ then $1.ord
          when /\A0x/ then token.hex
          else Integer(token)
          end
        end

        def numbers(text, name, size = nil)
          out = tokens(text, name).map { |t| number(t) }
          fail!("#{name}: #{out.size} entries, #{size} expected") if size && out.size != size
          out
        end

        # trans[][0x100]: each state's 256 next states, A (accept) as -1
        # and F (failure) as -2.
        def trans(text)
          body = text[/static const signed char trans\[\]\[0x100\] = \{(.*?)\n\};/m, 1] or fail!("no trans")
          rows = body.split(/\n\s*\},?/).map { |row| row.scan(/\b[AF]\b|\b\d+\b/) }.reject(&:empty?)
          rows.map do |row|
            fail!("a trans row of #{row.size}") unless row.size == 256

            row.map { |t| { "A" => -1, "F" => -2 }.fetch(t) { Integer(t) } }
          end
        end

        # CaseFoldMap: [[from, to], ...].
        def fold_map(text)
          body = text[/OnigPairCaseFoldCodes CaseFoldMap\[\] = \{(.*?)\n\};/m, 1] or return nil

          body.scan(/\{\s*(0x\h+),\s*(0x\h+)\s*\}/).map { |a, b| [a.hex, b.hex] }
        end

        # A static OnigCodePoint CR_ table as [count, low, high, ...],
        # with the #ifdef named by `defined` taken and every other one
        # left out.
        def code_ranges(text, name, defined)
          kept = +""
          stack = []
          active = true
          text.each_line do |line|
            case line
            when /\A#\s*(ifdef|ifndef|if)\b\s*(\w+)?/
              taken = case $1
                      when "ifdef" then defined.include?($2)
                      when "ifndef" then !defined.include?($2)
                      else $2 == "1"
                      end
              stack << [active, taken]
              active &&= taken
            when /\A#\s*else/
              parent, taken = stack.last
              active = parent && !taken
            when /\A#\s*endif/
              active, = stack.pop
            else
              kept << line if active
            end
          end
          values = kept[/CR_#{name}\[\] = \{(.*?)\};/m, 1].scan(/0x\h+|\b\d+\b/).map { |t| number(t) }
          fail!("CR_#{name}: #{values.size} values for #{values[0]} ranges") unless values.size == 1 + (values[0] * 2)

          values
        end

        # ASCII's ctype table and ISO-8859-1's lower-case table, which
        # regenc.c ships and several single-byte encodings share.
        def regenc = @regenc ||= Dev.cruby("regenc.c").gsub(%r{/\*.*?\*/}m, "")

        def ascii_ctype = @ascii_ctype ||= numbers(regenc, "OnigEncAsciiCtypeTable", 256)

        def iso_8859_1_lower = @iso_8859_1_lower ||= numbers(regenc, "OnigEncISO_8859_1_ToLowerCaseTable", 256)

        # What each encoding's OnigEncodingDefine names in the slots the
        # engine reads: [slot functions].
        def define_slots(text)
          body = text[/OnigEncodingDefine\(\w+, \w+\) = \{(.*?)\n\};/m, 1] or fail!("no OnigEncodingDefine")
          body = body.gsub(/#ifdef USE_CASE_MAP_API.*?#endif/m, "")
          body.split(",").map(&:strip).reject(&:empty?)
        end

        def function_body(text, suffix)
          i = text =~ /^(\w+_)?#{suffix}\s*\(/ or return nil

          text[i..][/\{.*?\n\}/m]
        end

        def single_byte_tables
          single = {}
          SINGLE_BYTE_FILES.each do |file|
            text = source("#{file}.c").gsub(/#if 0\b.*?#endif/m, "").gsub(/#ifdef USE_CASE_MAP_API\n.*?\n#endif/m, "")
            slots = define_slots(text)
            name = slots[1][/"(.*)"/, 1]
            ctype = numbers(text, text[/(\w+CtypeTable)\[256\]/, 1], 256)
            lower_name = text[/(\w+ToLowerCaseTable)\[256\]/, 1]
            lower = lower_name ? numbers(text, lower_name, 256) : nil

            fold = slots[8]
            entry = { ctype: ctype }
            if fold == "onigenc_ascii_mbc_case_fold"
              fail!("#{name}: ascii fold with its own apply") unless slots[9] == "onigenc_ascii_apply_all_case_fold" && slots[10] == "onigenc_ascii_get_case_fold_codes_by_str"

              entry[:fold] = :ascii
            else
              body = function_body(text, "mbc_case_fold")
              entry[:lower] = lower || (body.include?("ONIGENC_ISO_8859_1_TO_LOWER_CASE") ? iso_8859_1_lower : fail!("#{name}: no lower table"))
              entry[:sharp_s] = body.include?("SHARP_s")
              apply = function_body(text, "apply_all_case_fold")
              ess = apply[/CaseFoldMap, (\d)/, 1] or fail!("#{name}: apply_all_case_fold is not the map's")
              entry[:map] = fold_map(text)
              entry[:ess] = Integer(ess)
              by_str = function_body(text, "get_case_fold_codes_by_str")
              entry[:fold] = if (m = by_str[/CaseFoldMap, (\d)/, 1])
                                fail!("#{name}: the two maps disagree on ess-tsett") unless Integer(m) == entry[:ess]
                                :map
                              elsif file == "iso_8859_1"
                                :iso_8859_1
                              else
                                fail!("#{name}: get_case_fold_codes_by_str is its own")
                              end
            end
            code_ctype = function_body(text, "is_code_ctype").gsub(/\s+/, " ")
            fail!("#{name}: is_code_ctype is its own") unless code_ctype.include?("if (code < 256)") && code_ctype.include?("return FALSE;")

            single[name] = entry
          end
          single
        end

        def multibyte_tables
          multi = {}
          eucjp = source("euc_jp.c")
          multi["EUC-JP"] = { len: numbers(eucjp, "EncLen_EUCJP", 256), trans: trans(eucjp), map: fold_map(eucjp),
                              props: %w[Hiragana Katakana Han Latin Greek Cyrillic].to_h { |n| [n, code_ranges(eucjp, n, [])] } }
          sjis = source("shift_jis.h")
          multi["Shift_JIS"] = { len: numbers(sjis, "EncLen_SJIS", 256), trail: numbers(sjis, "SJIS_CAN_BE_TRAIL_TABLE", 256), trans: trans(sjis),
                                 map: fold_map(sjis), props: %w[Hiragana Katakana Han Latin Greek Cyrillic].to_h { |n| [n, code_ranges(sjis, n, [])] } }
          multi["Windows-31J"] = multi["Shift_JIS"].merge(props: %w[Hiragana Katakana Han Latin Greek Cyrillic].to_h { |n| [n, code_ranges(sjis, n, ["ENC_CP932"])] })
          big5 = source("big5.c")
          multi["Big5"] = { len: numbers(big5, "EncLen_BIG5", 256), trail: numbers(big5, "BIG5_CAN_BE_TRAIL_TABLE", 256), trans: trans(big5) }
          gbk = source("gbk.c")
          multi["GBK"] = { len: numbers(gbk, "EncLen_GBK", 256), trail: numbers(gbk, "GBK_CAN_BE_TRAIL_TABLE", 256), trans: trans(gbk) }
          cp949 = source("cp949.c")
          multi["CP949"] = { len: numbers(cp949, "EncLen_CP949", 256), trail: numbers(cp949, "CP949_CAN_BE_TRAIL_TABLE", 256), trans: trans(cp949) }
          euckr = source("euc_kr.c")
          multi["EUC-KR"] = { len: numbers(euckr, "EncLen_EUCKR", 256), trans: trans(euckr) }
          euctw = source("euc_tw.c")
          multi["EUC-TW"] = { len: numbers(euctw, "EncLen_EUCTW", 256), trans: trans(euctw) }
          gb18030 = source("gb18030.c")
          multi["GB18030"] = { map: tokens(gb18030, "GB18030_MAP").map { |t| %w[C1 C2 C4 CM].index(t) || fail!("GB18030_MAP: #{t}") }, trans: trans(gb18030) }
          fail!("GB18030_MAP: #{multi["GB18030"][:map].size} entries") unless multi["GB18030"][:map].size == 256

          emacs = source("emacs_mule.c")
          multi["Emacs-Mule"] = { len: numbers(emacs, "EncLen_EmacsMule", 256), trans: trans(emacs) }
          cesu = source("cesu_8.c")
          multi["CESU-8"] = { len: numbers(cesu, "EncLen_CESU8", 256), trans: trans(cesu) }

          MULTIBYTE_STATES.each do |name, states|
            fail!("#{name}: #{multi[name][:trans].size} states, #{states} expected") unless multi[name][:trans].size == states
          end
          multi
        end

        # Which Onigmo encoding each of ruby's own encodings reads with:
        # the first OnigEncodingDefine of a file is the encoding, and
        # ruby gives every later one in the same file the first as its
        # base (template/encdb.h.tmpl's ENC_SET_BASE), so Big5-HKSCS and
        # Big5-UAO read as Big5.
        def base_encodings(single, multi)
          defined = {}
          replicas = {}
          enc_files.each do |path|
            text = source(path)
            text = text.gsub(/#ifndef RUBY\n.*?#endif/m, "")
            first = nil
            text.scan(/OnigEncodingDefine\(\w+, \w+\) = \{\s*\w+,\s*"([^"]+)"/) do |(name)|
              if first
                replicas[name] = first
              else
                defined[name] = true
                first = name
              end
            end
            text.scan(/ENC_REPLICATE\("([^"]+)", "([^"]+)"\)/) { |name, base| replicas[name] = base }
          end
          bases = {}
          Encoding.list.reject(&:dummy?).each do |e|
            name = e.name
            name = replicas.fetch(name) until defined[name]
            bases[e.name] = name
          end
          known = single.keys + multi.keys + %w[ASCII-8BIT US-ASCII UTF-8 UTF-16LE UTF-16BE UTF-32LE UTF-32BE]
          missing = bases.values.uniq - known
          fail!("no tables for #{missing.join(", ")}") unless missing.empty?

          bases
        end

        # Every ctype bit to a POSIX bracket over every byte, and every
        # fold pair to a case-insensitive match, both under ruby itself.
        def hold_single_to_ruby(single)
          single.each do |name, entry|
            enc = Encoding.find(name)
            CTYPE_NAMES.each do |bit, posix|
              re = Regexp.new("[[:#{posix}:]]".encode(enc), Regexp::FIXEDENCODING)
              256.times do |b|
                want = entry[:ctype][b][bit] == 1
                got = re.match?(b.chr.force_encoding(enc))
                fail!("#{name}: byte #{b} [[:#{posix}:]] is #{got} under ruby, #{want} in the table") unless want == got
              end
            end
            # A pair the map folds together that the lower-case table
            # does not (ISO-8859-7's 0xD2, which no character holds)
            # folds in one direction alone under ruby too: the pairs are
            # reported, not refused, and the differential harness holds
            # the engine's use of both to ruby.
            apart = (entry[:map] || []).reject do |from, to|
              a = from.chr.force_encoding(enc)
              b = to.chr.force_encoding(enc)
              Regexp.new(Regexp.escape(a), Regexp::IGNORECASE | Regexp::FIXEDENCODING).match?(b) &&
                Regexp.new(Regexp.escape(b), Regexp::IGNORECASE | Regexp::FIXEDENCODING).match?(a)
            end
            warn "#{name}: #{apart.map { |f, t| format("%02X/%02X", f, t) }.join(" ")} fold one way only under ruby" unless apart.empty?
          end
        end

        # A lead byte's length, and each byte after it, against the byte
        # sequences ruby calls valid.
        def valid_lengths(name, len, trans, start = 0)
          enc = Encoding.find(name)
          256.times do |first|
            s = trans[start][first]
            one = [first].pack("C").force_encoding(enc).valid_encoding?
            fail!("#{name}: byte #{first} alone is #{one} under ruby") unless one == (s == -1)
            next unless s >= 0

            256.times do |second|
              t = trans[s][second]
              two = [first, second].pack("CC").force_encoding(enc).valid_encoding?
              fail!("#{name}: #{first} #{second} is #{two} under ruby") unless two == (t == -1)
            end
            fail!("#{name}: lead byte #{first} announces #{len[first]}") if len && len[first] < 2
          end
        end

        def hold_multibyte_to_ruby(multi)
          valid_lengths("EUC-JP", multi["EUC-JP"][:len], multi["EUC-JP"][:trans])
          valid_lengths("Shift_JIS", multi["Shift_JIS"][:len], multi["Shift_JIS"][:trans])
          valid_lengths("Big5", multi["Big5"][:len], multi["Big5"][:trans])
          valid_lengths("Big5-HKSCS", multi["Big5"][:len], multi["Big5"][:trans])
          valid_lengths("Big5-UAO", multi["Big5"][:len], multi["Big5"][:trans])
          valid_lengths("GBK", multi["GBK"][:len], multi["GBK"][:trans])
          valid_lengths("CP949", multi["CP949"][:len], multi["CP949"][:trans])
          valid_lengths("EUC-KR", multi["EUC-KR"][:len], multi["EUC-KR"][:trans])
          valid_lengths("EUC-TW", multi["EUC-TW"][:len], multi["EUC-TW"][:trans])
          valid_lengths("GB18030", nil, multi["GB18030"][:trans])
          valid_lengths("Emacs-Mule", multi["Emacs-Mule"][:len], multi["Emacs-Mule"][:trans])
          valid_lengths("CESU-8", multi["CESU-8"][:len], multi["CESU-8"][:trans])

          %w[EUC-JP Shift_JIS].each do |name|
            enc = Encoding.find(name)
            multi[name][:map].each do |from, to|
              a = [from].pack("n").force_encoding(enc)
              b = [to].pack("n").force_encoding(enc)
              fail!("#{name}: #{from.to_s(16)} and #{to.to_s(16)} do not fold together under ruby") unless Regexp.new(a, Regexp::IGNORECASE).match?(b)
            end
          end
        end

        # A binary String literal of `bytes`, in lines of 32 bytes.
        def literal(bytes)
          lines = bytes.each_slice(32).map { |row| row.map { |b| format("\\x%02X", b) }.join }
          "\"#{lines.join("\\\n")}\""
        end

        def u16(values) = literal(values.pack("v*").bytes)
        def u8(values) = literal(values.map { |v| v & 0xff })
        def u32(values) = literal(values.pack("V*").bytes)
        def pairs8(map) = map ? u8(map.flatten) : "nil"
        def state_table(rows) = u8(rows.flatten)
      end
    end
  end
end
