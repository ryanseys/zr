# frozen_string_literal: true

require_relative "../gen"

module Zr
  module Dev
    module Commands
      class Gen
        # Writes Ryu's two tables of powers of five, which the kernel's
        # shortest float printing reads (lib/zr/runtime/kernel/float.rb). They
        # are computed, as Ryu's own generator computes them, from exact
        # powers of five.
        class RyuTables < Generator
          writes "lib/zr/runtime/kernel/ryu_tables.rb"

          # The bits of each row (Ryu's DOUBLE_POW5_INV_BITCOUNT and
          # DOUBLE_POW5_BITCOUNT), and the row counts.
          BITS = 125
          INV_ROWS = 342
          ROWS = 326

          # Each row's 128-bit value as two little-endian words.
          def row_bytes(values) = values.flat_map { |value| [value & ((1 << 64) - 1), value >> 64] }.pack("Q<*").bytes

          # DOUBLE_POW5_INV_SPLIT: 2**(bits of 5**i - 1 + BITS) / 5**i, plus 1.
          def inverse = (0...INV_ROWS).map { |i| ((1 << ((5**i).bit_length - 1 + BITS)) / (5**i)) + 1 }

          # DOUBLE_POW5_SPLIT: the first BITS bits of 5**i.
          def powers
            (0...ROWS).map do |i|
              shift = (5**i).bit_length - BITS
              shift.negative? ? (5**i) << -shift : (5**i) >> shift
            end
          end

          def write(io)
            io.print <<~RUBY
              module Zr::Kern
                # Ryu's tables, generated by `zr-dev gen ryu_tables` from exact
                # powers of five: DOUBLE_POW5_INV_SPLIT (#{INV_ROWS} rows) and
                # DOUBLE_POW5_SPLIT (#{ROWS} rows), each row a 128-bit value as two
                # little-endian words.
                #
                # Derived from Ryu (Copyright 2018 Ulf Adams, Apache License 2.0 or Boost
                # Software License 1.0). See THIRD_PARTY_NOTICES.md and licenses/ryu.txt.

            RUBY
            emit_bytes(io, "zr_ryu_pow5_inv", row_bytes(inverse), nil)
            io.puts
            emit_bytes(io, "zr_ryu_pow5", row_bytes(powers), nil)
            io.puts "end"
          end
        end
      end
    end
  end
end
