# frozen_string_literal: true

require_relative "../gen"

module Zr
  module Dev
    module Commands
      class Gen
        # Writes the zone names that Date's loose parse knows, from CRuby's
        # ext/date/zonetab.list (RUBY_SRC). A row of the list is a name and
        # its offset in seconds, an expression such as `-(1*3600+1800)`,
        # which a small parser here reads; the list is never evaluated.
        class DateZonetab < Generator
          writes "lib/zr/runtime/ext/date/zonetab.rb"

          # The names and their offsets, in the list's order.
          def zones
            list = Dev.cruby("ext/date/zonetab.list").split(/^%%\n/).fetch(1)
            list.lines.map do |line|
              row = line.match(/\A([^,]+),\s*(.+?)\s*\z/) or raise "zonetab.list: no zone in #{line.inspect}"
              name, offset = row.captures
              [name, Offset.new(offset).value]
            end
          end

          def write(io)
            rows = zones.map { |name, offset| "#{name.inspect} => #{offset}" }
            io.print <<~RUBY
              # frozen_string_literal: true

              # The zone names a loose parse knows, and the offset of each in
              # seconds. Generated by `zr-dev gen date_zonetab` from ruby's
              # ext/date/zonetab.list; do not edit. Derived from CRuby's ext/date
              # (Ruby or BSD-2-Clause); see THIRD_PARTY_NOTICES.md.

              class Date
                ZONES = {
              #{rows.each_slice(4).map { |row| "    #{row.join(", ")}," }.join("\n")}
                }.freeze
                private_constant :ZONES
              end
            RUBY
          end

          # An offset of the list: integers under `+`, `-` and `*`, with
          # parentheses.
          class Offset
            def initialize(text)
              @tokens = text.scan(/\d+|[-+*()]/)
              raise "zonetab.list: #{text.inspect} is not an offset" unless @tokens.join == text.delete(" ")
            end

            def value
              sum.tap { raise "zonetab.list: #{@tokens.inspect} is left over" unless @tokens.empty? }
            end

            private

            def sum
              total = product
              while %w[+ -].include?(@tokens.first)
                sign = @tokens.shift
                total = sign == "+" ? total + product : total - product
              end
              total
            end

            def product
              total = unary
              while @tokens.first == "*"
                @tokens.shift
                total *= unary
              end
              total
            end

            def unary
              token = @tokens.shift
              case token
              when "-" then -unary
              when "+" then unary
              when "(" then sum.tap { @tokens.shift == ")" or raise "zonetab.list: no closing parenthesis" }
              when /\A\d+\z/ then Integer(token, 10)
              else raise "zonetab.list: a broken offset"
              end
            end
          end
        end
      end
    end
  end
end
