# frozen_string_literal: true

require_relative "../gen"

module Zr
  module Dev
    module Commands
      class Gen
        # docs/reference/support.md: what zr refuses, read from the compiler
        # itself. The syntax forms are the ones the HIR build and the
        # lowering refuse by name (`unsupported`); the libraries are the
        # names that `require` answers in the pinned ruby and that zr has no file
        # for (Build.missing_features); the baselines are the tests that each
        # target may fail. A refusal message links to this page.
        class Support < Generator
          writes "docs/reference/support.md"

          # The files that refuse a syntax form by name.
          FORMS_FROM = %w[lib/zr/hir/build.rb lib/zr/hir/build/*.rb lib/zr/lower.rb lib/zr/lower/**/*.rb].freeze

          def write(io)
            require_relative "../../lib/zr/refused"
            require_relative "../../lib/zr/hir"
            require_relative "../../lib/zr/hir/build"
            io.print(<<~MD)
              <!-- Generated by `zr-dev gen support`. Do not edit. -->
              # What zr supports

              zr compiles a Ruby program only when the binary gives exactly
              what ruby gives ([the contract](../explanation/the-contract.md)).
              Where it cannot promise that, it refuses the program with exit
              status 3 and names the form and its line. This page lists what
              zr refuses, as the compiler itself lists it. Other differences
              from ruby, all on purpose, are in
              [Differences from ruby](differences-from-ruby.md), and what each
              target can do is in [Targets](targets.md).

              ## Syntax that zr refuses

              The compiler refuses these forms by name. Any other syntax node
              that it does not know is refused with the node's name, for
              example `interpolated xstring (InterpolatedXString)`.

              #{forms.map { |form| "- #{form}" }.join("\n")}

              ## Libraries that a program cannot require

              A `require` of one of these names compiles, and raises
              `LoadError` with the reason when it runs, so a guarded
              require that never runs costs nothing. Every other library of
              the ruby that zr pins is there: the default and bundled gems, and ruby's
              own `lib/`. A gem that ruby does not ship comes from the gems that rubygems has
              installed, or from the Gemfile.lock that `BUNDLE_GEMFILE` names. A gem with a C extension needs a port, or
              `--native-ext` on macOS and on Linux (see
              [How to use a library or a gem](../how-to/use-a-library-or-gem.md)
              and [How to use a C extension](../how-to/use-a-c-extension.md)).

              #{libraries}

              ## Tests that a target may fail

              Each target can have a baseline: the program tests (below
              test/programs) that it may fail, each with the reason. A test in a
              baseline that passes fails the run, so these lists are current.

              #{baselines}
            MD
          end

          # The forms in `unsupported(node, "...")` calls. (Refused::FORMS only
          # gives words for a node, not a list of refusals.)
          def forms
            files = FORMS_FROM.flat_map { |glob| Dir[Dev.path(glob)] }.uniq.sort
            named = files.flat_map { |file| File.read(file).scan(/unsupported\((?:@l\.)?\w+(?:\.\w+)?, "([^"#]+)"\)/).flatten }
            # `unsupported(node, "#{kind} outside a block or loop")`, for break and next.
            kinds = files.flat_map { |file| File.read(file).scan(/unsupported\(\w+, "\#\{kind\} ([^"]+)"\)/).flatten }
            named += kinds.map { |rest| "`break` or `next` #{rest}" }
            named.map { |form| form.sub(/\A[a-z]/, &:upcase).sub("BEGIN { }", "`BEGIN { }`") }.uniq.sort
          end

          def libraries
            reasons = Hir::Build::UNSUPPORTED_LIBRARIES
            lists = Target.all.to_h do |target|
              encodings, rest = Hir::Build.missing_features(target).partition { |name| name.start_with?("enc/") }
              lines = rest.map { |name| reasons[name] ? "- #{reasons[name].sub(name, "`#{name}`").sub(/, so .*/, "")}" : "- `#{name}`" }
              unless encodings.empty?
                lines << "- #{encodings.size} encoding libraries under `enc/`: ruby loads them itself, and zr's runtime has every encoding built in"
              end
              [target.triple, lines.join("\n")]
            end
            # Targets with the same list share one heading.
            lists.group_by { |_, text| text }.map do |text, pairs|
              "### #{pairs.map { |triple, _| "`#{triple}`" }.join(", ")}\n\n#{text}"
            end.join("\n\n")
          end

          # The baselines of the targets. host.txt is the baseline of
          # `zr-dev host` (the kernel run on ruby), a check of zr's own, not
          # a target that a user builds for.
          def baselines
            Dir[Dev.path("test/baselines/*.txt")].sort.reject { |file| File.basename(file) == "host.txt" }.map do |file|
              rows = File.readlines(file, chomp: true).reject { |line| line.empty? || line.start_with?("#") }.map do |line|
                key, why = line.split("\t", 2)
                "| `#{key}` | #{why.to_s.gsub("|", "\\|")} |"
              end
              table = rows.empty? ? "None." : "| Test | Why |\n|---|---|\n#{rows.join("\n")}"
              "### #{File.basename(file, ".txt")}\n\n#{table}"
            end.join("\n\n")
          end
        end
      end
    end
  end
end
