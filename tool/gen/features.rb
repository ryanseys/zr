# frozen_string_literal: true

require_relative "../gen"

module Zr
  module Dev
    module Commands
      class Gen
        # Every name that `require` accepts in the ruby that `.ruby-version`
        # pins. zr refuses a require of such a name when it has no file for it.
        # For all other names, zr raises LoadError, as ruby does.
        class Features < Generator
          host_ruby!
          writes "lib/zr/hir/features.rb"

          # The Ruby and extension files below `root`, by path from it.
          def features(root)
            return [] unless File.directory?(root)

            Dir.glob("**/*.{rb,bundle,so}", base: root).grep_v(%r{\.dSYM/})
          end

          def write(io)
            require "rbconfig"
            require "rubygems"

            roots = [RbConfig::CONFIG["rubylibdir"], RbConfig::CONFIG["rubyarchdir"]]
            names = roots.flat_map { |root| features(root) }
            # A default gem's directory can hold more Ruby files than its
            # gemspec lists, from a later install of the same version. Only
            # the listed ones count.
            Gem::Specification.default_stubs.each do |stub|
              spec = stub.to_spec
              listed = spec.files.to_set
              spec.full_require_paths.each do |dir|
                rel = dir.delete_prefix("#{spec.full_gem_path}/")
                names.concat(features(dir).select { |name| name.end_with?(".rb") ? listed.include?("#{rel}/#{name}") : true })
              end
            end
            names = names.map { |rel| rel.sub(/\.(rb|bundle|so)\z/, "") }
            arch = File.basename(RbConfig::CONFIG["rubyarchdir"])
            names = names.grep_v(%r{\A#{Regexp.escape(arch)}/})
            names.concat(%w[complex enumerator rational thread])
            names = names.uniq.sort

            io.puts <<~HEAD
              # frozen_string_literal: true

              # Generated by `zr-dev gen features` from ruby #{RUBY_VERSION}. Do not edit.

              module Zr
                module Hir
                  # Every name `require` answers in ruby itself.
                  FEATURES = [
            HEAD
            names.each_slice(4) { |row| io.puts "      #{row.map(&:inspect).join(", ")}," }
            io.puts <<~TAIL
                  ].to_set.freeze
                end
              end
            TAIL
            warn "#{names.size} feature(s)"
          end
        end
      end
    end
  end
end
