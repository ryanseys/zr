# frozen_string_literal: true

require_relative "../gen"

module Zr
  module Dev
    class Gen
      # docs/explanation/performance.md: how fast a program that zr built
      # runs, and what a build costs, from the newest reports that
      # `zr-dev bench` and `zr-dev compile` committed under
      # benchmark/results/. Run `zr-dev bench` on the whole bank first;
      # this generator measures nothing itself.
      class Perf < Generator
        writes "docs/explanation/performance.md"

        Row = Data.define(:name, :build, :zr, :ruby, :yjit)

        # A program whose ruby time is under this many times ruby's start
        # (bm_startup) measures mostly the start, not the work.
        STARTUP_BOUND = 2.0

        def write(io)
          report = newest(Dir[Dev.path("benchmark/results/*.txt")])
          rows = rows(File.read(report))
          start = rows.find { |r| r.name == "bm_startup" } or fail!("#{Dev.rel(report)} has no bm_startup")
          timed, bound = rows.reject { |r| r.name == "bm_startup" }.partition { |r| r.ruby >= STARTUP_BOUND * start.ruby }
          io.print(<<~MD)
            <!-- Generated by `zr-dev gen perf` from #{Dev.rel(report)}#{compile_report && " and #{Dev.rel(compile_report)}"}. Do not edit. -->
            # Performance

            This page gives the newest measurements that are committed in
            `benchmark/results/`. #{header(File.read(report))} Read the
            numbers of one machine against each other only.
            [How to measure performance](../how-to/measure-performance.md)
            tells how to make them again.

            ## Run time

            Each program in `benchmark/` is built with zr, then run beside
            `ruby` and `ruby --yjit` (ruby 4.0.7). The harness checks each
            program's output against ruby's recording before it keeps a
            time. A ratio under 1 means zr's binary is faster.

            | | zr / ruby | zr / yjit |
            |---|---|---|
            | Geometric mean, #{timed.size} programs | #{ratio(gmean(timed.map { |r| r.zr / r.ruby }))} | #{ratio(gmean(timed.map { |r| r.zr / r.yjit }))} |
            | Start of an empty program (`bm_startup`) | #{ms(start.zr)} against #{ms(start.ruby)} | #{ms(start.zr)} against #{ms(start.yjit)} |

            The #{bound.size} programs that ruby runs in less than
            #{STARTUP_BOUND} times its own start are not in the mean,
            because their time is mostly the start of the process:
            #{bound.map { |r| "`#{r.name}`" }.join(", ")}.

            ### Slowest against YJIT

            #{table(timed.max_by(8) { |r| r.zr / r.yjit })}

            ### Fastest against YJIT

            #{table(timed.min_by(8) { |r| r.zr / r.yjit })}

            ### Known slow paths

            - **Bignum arithmetic on large numbers** (`bm_pidigits`): a
              bignum is an Array of 30-bit limbs in the runtime's Ruby
              (lib/zr/runtime/core/bignum.rb), multiplied and divided with the
              schoolbook methods. ruby uses GMP or Karatsuba-class methods
              in C for large operands.
            - **Regexp** (`bm_regexp_scan`): the engine is a port of Onigmo
              in Ruby, which the runtime compiles; ruby runs Onigmo's C.
            - **Small recursive methods** (`bm_ackermann`, `bm_tree_walker`):
              zr is faster than ruby here, but slower than YJIT.
            #{compile_section}
            ## All programs

            #{table((timed + bound).sort_by(&:name))}
          MD
        end

        def compile_report = @compile_report ||= newest(Dir[Dev.path("benchmark/results/compile/*.txt")])

        # The newest report: its name starts with its UTC stamp.
        def newest(files) = files.max_by { |f| File.basename(f) }

        def header(text)
          line = text.lines.first.to_s.delete_prefix("#").strip
          "The report is \"#{line}\"."
        end

        # Each program's block: its name and build time, then a row each for
        # zr, ruby and yjit with the real time in parentheses.
        def rows(text)
          text.split(/^(?=bm_)/).filter_map do |block|
            name, build = block[/\Abm_\S+/], block[/built in ([\d.]+) s/, 1]
            real = ->(who) { block[/^#{who}\s.*\(\s*([\d.]+)\)/, 1]&.to_f }
            next unless name && real.call("zr") && real.call("ruby") && real.call("yjit")

            Row.new(name, build.to_f, real.call("zr"), real.call("ruby"), real.call("yjit"))
          end
        end

        def table(rows)
          lines = rows.map do |r|
            "| `#{r.name}` | #{ms(r.zr)} | #{ms(r.ruby)} | #{ms(r.yjit)} | #{ratio(r.zr / r.ruby)} | #{ratio(r.zr / r.yjit)} |"
          end
          "| Program | zr | ruby | yjit | zr / ruby | zr / yjit |\n|---|---|---|---|---|---|\n#{lines.join("\n")}"
        end

        def compile_section
          return "" unless compile_report

          text = File.read(compile_report)
          body = text.lines.reject { |l| l.start_with?("#") || l.strip.empty? }.map(&:rstrip)
          head, *rest = body
          cols = head.split.drop(1) # the first word names the label column
          table = ["| Phase | #{cols.join(" | ")} |", "|---|#{"---|" * cols.size}"]
          rest.each do |line|
            label, values = line.split(/\s{2,}/, 2)
            table << "| #{label} | #{values.to_s.split.join(" | ")} |"
          end
          <<~MD

            ## Build time

            What a build costs, in seconds, with the runtime already built
            and cached. A name with `*` is the build by the compiled
            compiler; the others run the compiler under ruby.
            #{header(text)}

            #{table.join("\n")}
          MD
        end

        def gmean(values) = Math.exp(values.sum { |v| Math.log(v) } / values.size)
        def ratio(x) = format("%.2fx", x)
        def ms(seconds) = format("%.0f ms", seconds * 1000)
      end
    end
  end
end
