# frozen_string_literal: true

require_relative "../gen"

module Zr
  module Dev
    module Commands
      class Gen
        # Reads the Unicode case mappings from ruby, and writes them as tables
        # that the runtime uses to map characters.
        class Unicode < Generator
          host_ruby!
          writes "lib/zr/runtime/kernel/case_tables.rb"

          KINDS = {
            "UP" => :upcase.to_proc,
            "DOWN" => :downcase.to_proc,
            "TITLE" => :capitalize.to_proc,
            "SWAP" => :swapcase.to_proc
          }.freeze

          # Writes the single-character mappings as runs with the same delta.
          # Thus a table of 1,500 characters needs only a few hundred rows.
          def runs(table)
            table.keys.sort.each_with_object([]) do |cp, out|
              delta = table[cp] - cp
              last = out.last
              if last && last[0] + last[1] == cp && last[2] == delta
                last[1] += 1
              else
                out << [cp, 1, delta]
              end
            end
          end

          def char(cp)
            cp.chr(Encoding::UTF_8)
          rescue RangeError
            nil
          end

          def mappings
            single = Hash.new { |h, k| h[k] = {} }
            multi = Hash.new { |h, k| h[k] = {} }
            (0..0x10FFFF).each do |cp|
              next if (0xD800..0xDFFF).cover?(cp)
              next unless (c = char(cp))

              KINDS.each do |name, map|
                mapped = map.call(c)
                next if mapped == c

                codepoints = mapped.codepoints
                codepoints.size == 1 ? single[name][cp] = codepoints[0] : multi[name][cp] = codepoints
              end
            end
            [single, multi]
          end

          # Added to a delta so the table holds it as an unsigned word: no
          # mapping moves a character farther than the code space.
          BIAS = 0x200000

          def write(io)
            single, multi = mappings

            io.print <<~RUBY
              # Generated by `zr-dev gen unicode` from the pinned ruby's own case
              # mappings. Do not edit. Derived from the Unicode Character Database
              # (Unicode-3.0); see THIRD_PARTY_NOTICES.md.
              #
              # For each of upcase, downcase, capitalize and swapcase, the
              # characters that map to one other character, as runs with one delta,
              # and the characters that map to more than one. The case fold is
              # Onigmo's (zr_str_fold_utf8_m).

              module Zr::Kern
                # Added to each delta of the RUNS tables.
                CASE_BIAS = #{BIAS}

            RUBY
            KINDS.each_key do |name|
              runs = runs(single[name])
              rows = multi[name].sort.map { |from, to| [from, to.size, *to, *[0] * (3 - to.size)] }
              raise "#{name}: a mapping to more than three characters" if rows.any? { |row| row.size > 5 }

              words = [runs.size] + runs.flat_map { |first, count, delta| [first, count, delta + BIAS] }
              emit_bytes(io, "zr_case_#{name.downcase}_runs", words.pack("V*").bytes,
                         "#{name}: the count, then runs of three words sorted by code point (first, how many, delta + CASE_BIAS).")
              io.puts
              emit_bytes(io, "zr_case_#{name.downcase}_multi", ([rows.size] + rows.flatten).pack("V*").bytes,
                         "#{name}: the count, then rows of five words sorted by code point (from, how many, three codes).")
              io.puts
            end
            io.puts "end"
          end
        end
      end
    end
  end
end
