# frozen_string_literal: true

require_relative "../gen"
require_relative "../lib/zr/dev/gems"

module Zr
  module Dev
    class Gen
      # docs/reference/gem-compat.md: how far each gem in gems/compat.tsv
      # gets with zr, and the causes that stop the most gems. `zr-dev gems
      # sweep --save` writes the table; this generator runs no gem.
      class GemCompat < Generator
        writes "docs/reference/gem-compat.md"

        TIERS = {
          verified: "The probe and the gem's smoke program (`gems/<name>.rb`) give ruby's output.",
          loads: "The probe gives ruby's output.",
          compiles: "zr builds the probe, but the binary's output is not ruby's.",
          fails: "The build fails, or the tool cannot find or resolve the gem.",
          refused: "zr refuses the gem: it has a C extension that zr does not port, or it uses a form of Ruby that zr does not support.",
          skipped: "The tool did not try the gem: `gems/<name>.rb` skips it, or the probe fails under ruby too."
        }.freeze

        # The causes that the page lists.
        CAUSES = 15

        def write(io)
          table = Gems::Table.new(Gems::Table.compat)
          io.puts "<!-- Generated by `zr-dev gen gem-compat` from gems/compat.tsv. Do not edit. -->"
          io.print(<<~MD)
            # Gem compatibility

            This page lists the gems that `zr-dev gems` tried, and how far
            each one gets with zr. For each gem, the tool builds a small
            program (the probe) that requires the gem and prints each
            constant that the require defines. It runs the probe under ruby
            4.0.7 and as a zr binary, and compares the two outputs.
            [Check a gem](../how-to/check-a-gem.md) tells how to run it.

            | Tier | Meaning |
            |---|---|
            #{TIERS.map { |tier, text| "| #{tier} | #{text} |" }.join("\n")}
          MD
          if table.size.zero?
            io.puts "", "No gem has a row yet. Run `zr-dev gems sweep --save`."
            return
          end

          rows = table.to_a
          io.puts "", "The results come from #{commits(rows)}, on #{dates(rows)}.", ""
          summary(io, rows)
          causes(io, table)
          all(io, rows)
        end

        def summary(io, rows)
          counts = rows.map(&:tier).tally
          io.puts "## Summary", "", "| Tier | Gems |", "|---|---|"
          TIERS.each_key { |tier| io.puts "| #{tier} | #{counts.fetch(tier.to_s, 0)} |" }
          io.puts "| all | #{rows.size} |", ""
        end

        def causes(io, table)
          groups = Gems::Triage.new(table).groups
          return if groups.empty?

          io.puts "## What stops the most gems", ""
          io.puts "`zr-dev gems triage` gives this list, with the detail of each gem.", ""
          io.puts "| Cause | Gems | Most downloaded |", "|---|---|---|"
          groups.first(CAUSES).each { |group| io.puts "| `#{group.kind}` | #{group.rows.size} | #{group.gems.first(3).join(", ")} |" }
          io.puts "", "#{groups.size - CAUSES} more causes are in `gems/compat.tsv`." if groups.size > CAUSES
          io.puts ""
        end

        def all(io, rows)
          io.puts "## All gems", "", "The most downloaded first.", "", "| Gem | Version | Tier | Cause |", "|---|---|---|---|"
          rows.sort_by { |row| [-row.downloads.to_i, row.gem] }.each do |row|
            io.puts "| #{row.gem} | #{row.version} | #{row.tier} | #{row.kind.empty? ? "" : "`#{row.kind}`"} |"
          end
        end

        # "zr commit abc", or "3 zr commits" when the rows are of more than one.
        def commits(rows)
          seen = rows.map(&:zr_commit).reject(&:empty?).uniq
          seen.one? ? "zr commit #{seen.first}" : "#{seen.size} zr commits"
        end

        # "2026-09-29", or "2026-09-01 to 2026-09-29".
        def dates(rows)
          seen = rows.map(&:date).reject(&:empty?).uniq.sort
          seen.one? ? seen.first : "#{seen.first} to #{seen.last}"
        end
      end
    end
  end
end
