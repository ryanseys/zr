# frozen_string_literal: true

# The emoji the carriers' UTF-8 encodings exchange, read off ruby's own
# enc/trans/emoji-exchange-tbl.rb at ruby 4.0.6's revision:
#
#   ruby tools/emoji.rb > rt/core/emoji.rb
#
# A row of a pair holds, in hex, the code point a character has in the
# source, then `>` and the code points it becomes; a code point alone is
# one the target has no emoji for.
REVISION = "03b6d3f8898a28604fe6cb00eae3226b821168f4"
CHECKOUT = File.expand_path("~/dev/github.com/ruby/ruby")

eval(IO.popen(["git", "-C", CHECKOUT, "show", "#{REVISION}:enc/trans/emoji-exchange-tbl.rb"], &:read), TOPLEVEL_BINDING)

def points(hex) = [hex].pack("H*").force_encoding(Encoding::UTF_8).codepoints.map { |point| format("%X", point) }

pairs = EMOJI_EXCHANGE_TBL.flat_map do |from, targets|
  targets.map do |to, rows|
    cells = rows.map do |source, target|
      source = points(source).join
      target == :undef ? source : "#{source}>#{points(target).join('+')}"
    end
    lines = cells.each_slice(12).map { |slice| "      #{"#{slice.join(' ')} ".inspect}" }
    "    #{[from, to].inspect} =>\n#{lines.join(" \\\n")},"
  end
end

puts <<~RUBY
  # The emoji UTF8-DoCoMo, UTF8-KDDI and UTF8-SoftBank exchange with each
  # other and with Unicode, from ruby's enc/trans/emoji-exchange-tbl.rb.
  # Generated by tools/emoji.rb; do not edit.
  class Encoding
    CARRIERS = ["UTF8-DoCoMo", "UTF8-KDDI", "UTF8-SoftBank"].freeze

    # Each pair's rows: `from>to` in hex code points, `+` between the
    # code points of a target that takes two, and `from` alone for one
    # the target has no emoji for.
    EMOJI_ROWS = {
  #{pairs.join("\n")}
    }.freeze
    EMOJI = {}
    private_constant :CARRIERS, :EMOJI_ROWS, :EMOJI

    def self.carrier?(encoding)
      Primitive.attr! :hidden
      CARRIERS.include?(encoding.name)
    end

    # The exchange from one encoding to another, read once: each code
    # point it names, and the code points it becomes, or nil for none.
    def self.emoji(from, to)
      Primitive.attr! :hidden
      EMOJI[[from.name, to.name]] ||= EMOJI_ROWS.fetch([from.name, to.name]).split.to_h do |row|
        source, target = row.split(">")
        [source.hex, target&.split("+")&.map(&:hex)]
      end
    end
    private_class_method :carrier?, :emoji
  end
RUBY
