# How the runtime walks a String in a multibyte encoding, written as
# rt/kernel/enc_mb.rb from the Onigmo encoders Regexp reads with
# (rt/core/regexp/onig/encoding_multibyte.rb). A String and a Regexp
# over it then agree on every character: both read the lead-byte
# lengths and state tables of CRuby's enc/*.c, through the same
# descriptor the matcher takes.
#
#   ruby tools/enc_mb.rb
#
# The descriptors are held to ruby first: every one- and two-byte
# sequence, and a sample of longer ones, must be valid where
# String#valid_encoding? says so.
require_relative "../lib/ze0/zr"

abort "ruby 4.0.6 records these tables; this is #{RUBY_VERSION}" unless RUBY_VERSION == "4.0.6"

Ze0::Zr.require_onig

ROOT = File.expand_path("..", __dir__)
OUT = File.join(ROOT, "rt/kernel/enc_mb.rb")
Enc = Regexp::Onig::Enc

def index_of(encoding) = Encoding.list.index(encoding)

# The encodings a String walks with an encoder of their own: ASCII meets
# them, a character spans bytes, and they are not UTF-8 under a name.
readers = Encoding.list.reject(&:dummy?).select(&:ascii_compatible?)
utf8_like = readers.select { |encoding| encoding != Encoding::UTF_8 && Regexp::Onig::EncTables::BASES[encoding.name] == "UTF-8" }
mb = (readers - utf8_like).select { |encoding| Enc.for(encoding).max_len > 1 && encoding != Encoding::UTF_8 }
bases = mb.group_by { |encoding| Enc.for(encoding) }

# Whether the bytes are one whole character, as precise_mbc_enc_len of
# the encoder the descriptor is written from answers.
def found?(enc, bytes)
  n = enc.precise_len(bytes, 0, bytes.bytesize)
  n == bytes.bytesize
end

random = Random.new(1)
bases.each do |enc, encodings|
  encodings.each do |encoding|
    sequences = (0x80..0xFF).map { |a| [a] }
    sequences += (0x80..0xFF).flat_map { |a| (0..0xFF).map { |b| [a, b] } }
    sequences += Array.new(100_000) { Array.new(random.rand(3..6)) { random.rand(3).zero? ? random.rand(0x30..0x39) : random.rand(0x80..0xFF) } }
    sequences.each do |bytes|
      text = bytes.pack("C*")
      ours = found?(enc, text.b)
      theirs = text.dup.force_encoding(encoding).valid_encoding? && text.dup.force_encoding(encoding).length == 1
      abort "#{encoding.name} #{text.unpack1('H*')}: ruby says #{theirs}, the descriptor #{ours}" unless ours == theirs
    end
  end
end

def ranges(list)
  out = []
  list.sort.each do |n|
    if out.last && out.last[1] == n - 1
      out.last[1] = n
    else
      out << [n, n]
    end
  end
  out
end

def test(name, list)
  ranges(list).map { |from, to| from == to ? "#{name} == #{from}" : "#{name} >= #{from} && #{name} <= #{to}" }.join(" || ")
end

def bytes_literal(bytes)
  lines = bytes.bytes.each_slice(32).map { |row| row.map { |b| format("\\x%02x", b) }.join }
  "\"#{lines.join("\\\n")}\""
end

def def_name(enc) = "zr_enc_mb_#{enc.name.downcase.tr('-', '_')}"

kernel = +<<~HEAD
  # How a String in a multibyte encoding is walked, generated by
  # tools/enc_mb.rb from the Onigmo encoders Regexp reads with. Each
  # encoding's descriptor (Regexp::Onig::Enc::Base#descriptor) holds the
  # lead-byte lengths and state tables of its enc/*.c file, and the
  # matcher's own zr_onig_precise_len walks them, so a String and a
  # Regexp over it read the same characters.

  # Whether the encoding `index` names holds characters that span bytes
  # in a way of its own: not UTF-8, not UTF-16 or UTF-32, and not one
  # byte one character.
  sig [Word] => Bool
  machine def zr_enc_mb_p(index)
    #{test('index', mb.map { |e| index_of(e) })}
  end

  # Whether the encoding writes its characters as UTF-8 writes them.
  sig [Word] => Bool
  machine def zr_enc_utf8_like_p(index)
    #{test('index', utf8_like.map { |e| index_of(e) })}
  end

  # The descriptor a multibyte encoding is walked with, or 0 for any
  # other encoding.
  sig [Word] => Word
  machine def zr_enc_mb_descriptor(index)
HEAD
blobs = bases.group_by { |enc, _| enc.descriptor }.to_h { |_, pairs| [pairs.first.first, pairs.flat_map(&:last)] }
blobs.each do |enc, encodings|
  kernel << "  # #{encodings.map(&:name).join(', ')}\n"
  kernel << "  if #{test('index', encodings.map { |e| index_of(e) })}\n"
  kernel << "    return Machine.word(#{def_name(enc)})\n  end\n"
end
kernel << "  0\nend\n"
blobs.each_key do |enc|
  kernel << "\nsig [] => Ptr\nmachine def #{def_name(enc)}\n"
  kernel << "  Machine.bytes(\n  #{bytes_literal(enc.descriptor)})\nend\n"
end
File.write(OUT, kernel)
warn "#{blobs.size} descriptors for #{mb.size} encodings, #{kernel.bytesize} bytes"
