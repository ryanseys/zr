# The Fcntl table, read off ruby and written as the module the runtime
# carries. Every value is this platform's own -- O_NOCTTY is 0x20000 here
# and 0x100 on Linux -- which is why they are read rather than written
# down, as CRuby reads them from the headers.
#
#   ruby tools/fcntl.rb > rt/ext/fcntl.rb
require "fcntl"

GROUPS = {
  "The fcntl(2) commands, of which POSIX numbers the first five." =>
    %w[F_DUPFD F_GETFD F_SETFD F_GETFL F_SETFL F_GETLK F_SETLK F_SETLKW],
  "The one flag F_SETFD carries." => %w[FD_CLOEXEC],
  "The kinds of lock a lock command asks for." => %w[F_RDLCK F_WRLCK F_UNLCK],
  "The access modes of open(2), and the mask that reads them back." =>
    %w[O_RDONLY O_WRONLY O_RDWR O_ACCMODE],
  "The status flags, each a bit of its own. O_NDELAY is the older " \
  "spelling of O_NONBLOCK and names the same bit." =>
    %w[O_APPEND O_CREAT O_EXCL O_TRUNC O_NONBLOCK O_NDELAY O_NOCTTY]
}.freeze

named = GROUPS.values.flatten + ["VERSION"]
rest = Fcntl.constants.map(&:to_s).sort - named

puts "# frozen_string_literal: true"
puts
puts "# `require \"fcntl\"`: the names of the fcntl(2) commands and the flags"
puts "# they carry. The module is a table and nothing else; the calls that use"
puts "# it are IO's own. Generated by tools/fcntl.rb from ruby's Fcntl."
puts "module Fcntl"
puts "  VERSION = #{Fcntl::VERSION.inspect}"
GROUPS.each do |note, names|
  puts
  note.scan(/.{1,68}(?:\s|\z)/) { |line| puts "  # #{line.strip}" }
  names.each { |name| puts "  #{name} = #{Fcntl.const_get(name)}" }
end
unless rest.empty?
  puts
  puts "  # What this platform adds of its own."
  rest.each { |name| puts "  #{name} = #{Fcntl.const_get(name)}" }
end
puts "end"
