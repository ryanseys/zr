# The byte tables of the single-byte encodings, read off ruby.
#
#   ruby tools/transcode.rb > rt/core/transcode.rb
# Bytes below 128 stand for themselves in every one of them, so a row
# holds bytes 128 to 255 alone: four hex digits for the code point the
# byte reads as, `----` where the encoding leaves the byte out.
pairs = (0..255).flat_map { |a| (0..255).map { |b| [a, b].pack("CC") } }

single = Encoding.list.reject(&:dummy?).select do |encoding|
  pairs.none? { |text| (text.force_encoding(encoding).length == 1 rescue false) }
end

rows = single.filter_map do |encoding|
  next if encoding == Encoding::BINARY || encoding == Encoding::US_ASCII

  points = (128..255).map do |byte|
    code = ([byte].pack("C").force_encoding(encoding).encode("UTF-8").ord rescue nil)
    code ? format("%04X", code) : "----"
  end
  "  #{encoding.name.inspect} => #{points.join.inspect},"
end

# How ruby words a conversion error for each encoding: the name its
# converter answers to, and whether a one-step conversion reads as
# `X from A to B` rather than as a chain. Both are read off a
# deliberate failure. A converter that does not exist at all says so.
UNMAPPED = "\u{1F600}"
PIVOT = Encoding::UTF_8

def shape(encoding)
  message = (UNMAPPED.encode(encoding) rescue $!.message)
  return nil if message.start_with?("code converter not found")

  short = !message.include?(" in conversion from ")
  step = short ? encoding.name : message[/\AU\+\h+ to (.*?) in conversion from /, 1]
  [short, step, from_shape(encoding)]
end

# The same question for the other direction, asked with a byte the
# encoding leaves out. An encoding with no such byte never raises here,
# so its answer does not matter and follows the other direction.
def from_shape(encoding)
  byte = (128..255).find { |b| ([b].pack("C").force_encoding(encoding).encode("UTF-8") rescue nil).nil? }
  return true if byte.nil?

  message = ([byte].pack("C").force_encoding(encoding).encode("UTF-8") rescue $!.message)
  !message.include?(" in conversion from ")
end

# Whether the encoding cases its non-ASCII characters at all. The ones
# that do follow Unicode over their own code points; the rest touch
# nothing but the ASCII half.
cased = single.select do |encoding|
  next false if encoding == Encoding::BINARY || encoding == Encoding::US_ASCII

  (128..255).any? { |byte| [byte].pack("C").force_encoding(encoding).upcase.bytes != [byte] }
end

shapes = single.filter_map do |encoding|
  row = shape(encoding)
  next "  #{encoding.name.inspect} => nil," if row.nil?

  "  #{encoding.name.inspect} => [#{row[0]}, #{row[1].inspect}, #{row[2]}],"
end

puts <<~HEADER
  # The single-byte encodings' tables, generated by tools/transcode.rb.
  # A row holds bytes 128 to 255: four hex digits for the code point the
  # byte reads as, `----` where the encoding leaves the byte out. Bytes
  # below 128 stand for themselves in every one of these encodings.
  class Encoding
    HIGH = {
  #{rows.join("\n").gsub(/^/, "  ")}
    }.freeze
    private_constant :HIGH

    # How a conversion error reads: whether a one-step conversion to
    # this encoding words as `X from A to B` rather than as a chain,
    # the name the converter answers to, and the same short-form
    # question for a conversion away from it. A nil row is an encoding
    # with no converter at all.
    SHAPES = {
  #{shapes.join("\n").gsub(/^/, "  ")}
    }.freeze
    private_constant :SHAPES

    # The encodings that case their non-ASCII characters, which they do
    # as Unicode does. Every other single-byte encoding folds the ASCII
    # half alone.
    CASED = [
  #{cased.map { |e| "  #{e.name.inspect}," }.join("\n").gsub(/^/, "  ")}
    ].freeze
    private_constant :CASED
  end
HEADER
