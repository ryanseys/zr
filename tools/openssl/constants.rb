# frozen_string_literal: true

# Writes rt/ext/openssl/ossl/constants.rb: every Integer constant ruby's
# openssl extension defines in C, with the value ruby answers, in the
# order ruby defined them. The values are the OpenSSL 3 headers' macros,
# which the port cannot read, so ruby, the oracle, gives them.
#
#   ruby tools/openssl/constants.rb > rt/ext/openssl/ossl/constants.rb
require "openssl"

rows = []
walk = lambda do |mod, seen|
  next if seen[mod]

  seen[mod] = true
  mod.constants(false).each do |name|
    value = mod.const_get(name)
    if value.is_a?(Module)
      walk.(value, seen) if value.name == "#{mod.name}::#{name}"
    elsif value.is_a?(Integer) && mod.const_source_location(name)&.first.to_s.end_with?(".bundle", ".so")
      rows << [mod.name, name, value] unless mod == OpenSSL && name == :OPENSSL_VERSION_NUMBER
    end
  end
end
walk.(OpenSSL, {})

puts "# frozen_string_literal: true"
puts
puts "# Generated by tools/openssl/constants.rb from ruby #{RUBY_VERSION}'s openssl"
puts "# #{OpenSSL::VERSION}. Do not edit."
puts "module OpenSSL"
rows.chunk { |mod, _, _| mod }.each_with_index do |(mod, group), i|
  puts unless i.zero?
  scope = mod.delete_prefix("OpenSSL").delete_prefix("::")
  group.each do |_, name, value|
    text = value.negative? || value < 0x10000 ? value.to_s : format("0x%x", value)
    puts "  #{scope.empty? ? "" : "#{scope}::"}#{name} = #{text}"
  end
end
puts "end"
