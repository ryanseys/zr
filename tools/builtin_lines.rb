# frozen_string_literal: true

# The lines of the methods CRuby writes in Ruby, read off its builtin
# sources at ruby 4.0.6's revision, for the :call and :return events
# TracePoint gives them:
#
#   ruby tools/builtin_lines.rb > rt/core/builtin_lines.rb
#
# Each method is keyed `Owner#name`, or `Owner.name` for a singleton
# method, and holds its `<internal:file>` path, the line its def starts
# on, and the line its body ends on, which is where ruby reports the
# return.
require "prism"

REVISION = "03b6d3f8898a28604fe6cb00eae3226b821168f4"
CHECKOUT = File.expand_path("~/dev/github.com/ruby/ruby")
SOURCES = %w[ast dir gc numeric io marshal pack trace_point warning array hash kernel pathname_builtin ractor
             symbol timev thread_sync nilclass prelude].freeze

# The defs of one file, with the class and module names around each.
class Defs < Prism::Visitor
  attr_reader :rows

  def initialize(path)
    super()
    @path = path
    @scope = []
    @singleton = false
    @rows = {}
  end

  def visit_class_node(node) = within(node.constant_path.slice) { super }

  # A def inside `with_jit` stands only while a JIT runs; without one the
  # method stays C's.
  def visit_call_node(node)
    super unless node.name == :with_jit && node.receiver.nil?
  end
  def visit_module_node(node) = within(node.constant_path.slice) { super }

  def visit_singleton_class_node(node)
    was = @singleton
    @singleton = node.expression.is_a?(Prism::SelfNode)
    super
  ensure
    @singleton = was
  end

  def visit_def_node(node)
    owner = @scope.join("::")
    owner = "Object" if owner.empty?
    singleton = @singleton || node.receiver.is_a?(Prism::SelfNode)
    key = "#{owner}#{singleton ? '.' : '#'}#{node.name}"
    @rows[key] ||= [@path, call_line(node), node.location.end_line]
  end

  private

  # The def's own line, but for a method split on
  # `Primitive.mandatory_only?`, whose sequence starts at that test.
  def call_line(node)
    first = node.body.is_a?(Prism::StatementsNode) ? node.body.body.first : nil
    split = first.is_a?(Prism::IfNode) && first.predicate.slice == "Primitive.mandatory_only?"
    split ? first.location.start_line : node.location.start_line
  end

  def within(name)
    @scope.push(name)
    yield
  ensure
    @scope.pop
  end
end

rows = {}
SOURCES.each do |name|
  source = IO.popen(["git", "-C", CHECKOUT, "show", "#{REVISION}:#{name}.rb"], &:read)
  defs = Defs.new("<internal:#{name}>")
  Prism.parse(source).value.accept(defs)
  rows.merge!(defs.rows) { |_key, first, _later| first }
end

puts "# frozen_string_literal: true"
puts
puts "# Generated by tools/builtin_lines.rb from ruby 4.0.6's builtin sources. Do not edit."
puts "#"
puts "# Where CRuby's own Ruby methods stand: the path TracePoint names for"
puts "# one, the line its :call reports, and the line its :return reports."
puts "class TracePoint"
puts "  BUILTIN_LINES = {"
rows.sort.each { |key, (path, first, last)| puts "    #{key.inspect} => [#{path.inspect}, #{first}, #{last}]," }
puts "  }.freeze"
puts "  private_constant :BUILTIN_LINES"
puts "end"
