# The three kernel tables a lowering reads, written as the text an eval
# carries instead of the kernel sources. Each OS layer's kernel has its
# own, so the target names which.
#
#   ruby -Ilib tools/description.rb [triple] > rt/ext/os/<os>/zr_description.rb
require "ze0/zr"

target = ARGV.empty? ? Ze0::Target.default : Ze0::Target.fetch(ARGV.first) || abort("no target #{ARGV.first}")
text = Ze0::Machine::Description.of(Ze0::Zr.runtime(target).unit).to_text

puts "# Generated by tools/description.rb from rt/kernel. Do not edit."
puts "module Ze0"
puts "  module Machine"
puts "    class Description"
puts "      KERNEL = <<~ROWS"
text.each_line { |line| puts "        #{line}" }
puts "      ROWS"
puts "    end"
puts "  end"
puts "end"
