# Writes lib/ze0/hir/features.rb: every name `require` answers in the
# ruby the .ruby-version pins. ze0 refuses a require of one it has no
# file for, and lets every other name raise LoadError as ruby does.
require "rbconfig"
require "rubygems"
require "set"

roots = [RbConfig::CONFIG["rubylibdir"], RbConfig::CONFIG["rubyarchdir"]]
Gem::Specification.default_stubs.each { |stub| roots.concat(stub.full_require_paths) }

names = roots.uniq.select { |root| File.directory?(root) }.flat_map do |root|
  Dir.glob("**/*.{rb,bundle,so}", base: root).grep_v(%r{\.dSYM/}).map { |rel| rel.sub(/\.(rb|bundle|so)\z/, "") }
end
arch = File.basename(RbConfig::CONFIG["rubyarchdir"])
names = names.grep_v(%r{\A#{Regexp.escape(arch)}/})
names.concat(%w[complex enumerator ractor rational thread])
names = names.uniq.sort

rows = names.each_slice(4).map { |row| "      #{row.map(&:inspect).join(", ")}," }
head = <<~HEAD
  # frozen_string_literal: true

  # Generated by tools/features.rb from ruby #{RUBY_VERSION}. Do not edit.

  module Ze0
    module Hir
      # Every name `require` answers in ruby itself.
      FEATURES = [
HEAD
tail = <<~TAIL
      ].to_set.freeze
    end
  end
TAIL
File.write(File.expand_path("../lib/ze0/hir/features.rb", __dir__), head + rows.join("\n") + "\n" + tail)
puts "#{names.size} feature(s)"
