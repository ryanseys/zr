# The encoding registry, read off ruby and written as a table the
# runtime builds its Encoding objects from.
#
#   ruby tools/encodings.rb > rt/core/encodings.rb
# `inspect` before anything touches an encoding says whether its table
# is already in ruby, which is the state a fresh program starts from.
loaded = Encoding.list.to_h { |encoding| [encoding.name, !encoding.inspect.include?("(autoload)")] }

# Whether one byte is always one character: no pair of bytes anywhere
# in the encoding forms a single character.
pairs = (0..255).flat_map { |a| (0..255).map { |b| [a, b].pack("CC") } }
bytewise = Encoding.list.to_h do |encoding|
  [encoding.name, pairs.none? { |text| (text.force_encoding(encoding).length == 1 rescue false) }]
end

rows = Encoding.list.map do |encoding|
  names = encoding.names.map(&:inspect).join(", ")
  "  [[#{names}], #{encoding.dummy?}, #{encoding.ascii_compatible?}, #{loaded[encoding.name]}, #{bytewise[encoding.name]}],"
end

# The constants, in the order ruby defines them, each naming the
# encoding it stands for.
constants = Encoding.constants.filter_map do |const|
  value = Encoding.const_get(const)
  next unless value.is_a?(Encoding)

  "  [#{const.to_s.inspect}, #{value.name.inspect}],"
end

puts <<~HEADER
  # The encodings ruby knows, generated by tools/encodings.rb, in ruby's
  # own index order. A row is the canonical name with its aliases,
  # whether the encoding is a dummy one, whether its bytes below 128
  # are ASCII, whether a fresh program has its table already, and
  # whether one byte is always one character. The second table is the
  # constant each encoding answers to.
  class Encoding
    UNICODE_VERSION = #{Encoding::UNICODE_VERSION.inspect}

    ROWS = [
  #{rows.join("\n").gsub(/^/, "  ")}
    ].freeze
    private_constant :ROWS

    CONSTANTS = [
  #{constants.join("\n").gsub(/^/, "  ")}
    ].freeze
    private_constant :CONSTANTS
  end
HEADER
