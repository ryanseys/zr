# The sysconf, confstr and pathconf names Etc answers, read off ruby and
# written as the table the extension defines its constants from, with
# the members of Etc::Passwd and Etc::Group, which follow the fields this
# OS's struct passwd and struct group have. An OS with no group database
# has no Etc::Group.
#
#   ruby tools/etc.rb
require "etc"
require_relative "layer"

rows = Etc.constants.sort.filter_map do |name|
  value = Etc.const_get(name)
  [name, value] if value.is_a?(Integer)
end

out = +"# Generated by tools/etc.rb from ruby's own etc. Do not edit.\nmodule Etc\n"
rows.each { |name, value| out << "  #{name} = #{value}\n" }
structs = { "PASSWD_MEMBERS" => :Passwd, "GROUP_MEMBERS" => :Group }.select { |_, name| Etc.const_defined?(name, false) }
out << "\n"
structs.each { |constant, name| out << "  #{constant} = %i[#{Etc.const_get(name).members.join(" ")}].freeze\n" }
out << "  private_constant #{structs.keys.map { |constant| ":#{constant}" }.join(", ")}\n"
out << "end\n"
Layer.write("ext", "etc_names.rb", out)
