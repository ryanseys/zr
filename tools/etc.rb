# The sysconf, confstr and pathconf names Etc answers, read off ruby and
# written as the table the extension defines its constants from.
#
#   ruby tools/etc.rb > rt/ext/etc_names.rb
require "etc"

rows = Etc.constants.sort.filter_map do |name|
  value = Etc.const_get(name)
  [name, value] if value.is_a?(Integer)
end

puts "# Generated by tools/etc.rb from ruby's own etc. Do not edit."
puts "module Etc"
rows.each { |name, value| puts "  #{name} = #{value}" }
puts "end"
