  # MD5, SHA-1, SHA-256, SHA-512 (also used for SHA-384) and RIPEMD-160.
  # Each one reads whole blocks and updates the chaining words in place.
  # The Ruby part of the extension pads the message and keeps the bytes
  # that do not fill a block. A state is a binary String of 64-bit
  # little-endian slots, one slot for each word.
  DIGEST_MD5 = 0
  DIGEST_SHA1 = 1
  DIGEST_SHA256 = 2
  DIGEST_SHA512 = 3
  DIGEST_RMD160 = 4
  DIGEST_MASK32 = 4294967295

