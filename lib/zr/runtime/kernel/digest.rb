  # Returns the initial chaining words of algorithm `row` as a state
  # (0 MD5, 1 SHA-1, 2 SHA-256, 3 SHA-512, 4 SHA-384, 5 RIPEMD-160).
  #: (value) -> value
  def zr_digest_state(row)
    zr_str_new(zr_digest_iv() + (zr_fix2long(row) * 64), 64)
  end

  #: (ptr) -> ptr
  def zr_digest_le32(p)
    Machine.ptr(Machine.u32(Machine.load32(p, 0)))
  end

  #: (ptr) -> ptr
  def zr_digest_be32(p)
    b0 = Machine.ptr(Machine.u8(Machine.load8(p, 0)))
    b1 = Machine.ptr(Machine.u8(Machine.load8(p, 1)))
    b2 = Machine.ptr(Machine.u8(Machine.load8(p, 2)))
    b3 = Machine.ptr(Machine.u8(Machine.load8(p, 3)))
    (b0 << 24) | (b1 << 16) | (b2 << 8) | b3
  end

  #: (ptr) -> ptr
  def zr_digest_be64(p)
    (zr_digest_be32(p) << 32) | zr_digest_be32(p + 4)
  end

  #: (ptr, word) -> ptr
  def zr_digest_rotl32(x, n)
    ((x << n) | (x >> (32 - n))) & DIGEST_MASK32
  end

  #: (ptr, word) -> ptr
  def zr_digest_rotr64(x, n)
    (x >> n) | Machine.ushl_wrap(x, 64 - n)
  end

  #: (ptr, word) -> ptr
  def zr_digest_word(h, i)
    Machine.ptr(Machine.load64(h + (i * 8), 0))
  end

  #: (ptr, word, ptr) -> void
  def zr_digest_set(h, i, v)
    Machine.store64(h + (i * 8), 0, Machine.word(v))
  end

  #: (ptr, ptr) -> void
  def zr_md5_block(h, p)
    k = zr_md5_k()
    steps = zr_md5_shifts()
    a = zr_digest_word(h, 0)
    b = zr_digest_word(h, 1)
    c = zr_digest_word(h, 2)
    d = zr_digest_word(h, 3)
    i = 0
    while i < 64
      f = b ^ c ^ d
      if i < 16
        f = (b & c) | ((b ^ DIGEST_MASK32) & d)
      elsif i < 32
        f = (d & b) | ((d ^ DIGEST_MASK32) & c)
      elsif i >= 48
        f = c ^ (b | (d ^ DIGEST_MASK32))
      end
      g = Machine.u8(Machine.load8(steps + 64 + i, 0))
      s = Machine.u8(Machine.load8(steps + i, 0))
      f = (f + a + zr_digest_word(k, i) + zr_digest_le32(p + (g * 4))) & DIGEST_MASK32
      a = d
      d = c
      c = b
      b = (b + zr_digest_rotl32(f, s)) & DIGEST_MASK32
      i = i + 1
    end
    zr_digest_set(h, 0, (zr_digest_word(h, 0) + a) & DIGEST_MASK32)
    zr_digest_set(h, 1, (zr_digest_word(h, 1) + b) & DIGEST_MASK32)
    zr_digest_set(h, 2, (zr_digest_word(h, 2) + c) & DIGEST_MASK32)
    zr_digest_set(h, 3, (zr_digest_word(h, 3) + d) & DIGEST_MASK32)
  end

  #: (ptr, ptr) -> void
  def zr_sha1_block(h, p)
    w = Machine.slot(640)
    i = 0
    while i < 16
      zr_digest_set(w, i, zr_digest_be32(p + (i * 4)))
      i = i + 1
    end
    while i < 80
      x = zr_digest_word(w, i - 3) ^ zr_digest_word(w, i - 8) ^ zr_digest_word(w, i - 14) ^ zr_digest_word(w, i - 16)
      zr_digest_set(w, i, zr_digest_rotl32(x, 1))
      i = i + 1
    end
    a = zr_digest_word(h, 0)
    b = zr_digest_word(h, 1)
    c = zr_digest_word(h, 2)
    d = zr_digest_word(h, 3)
    e = zr_digest_word(h, 4)
    i = 0
    while i < 80
      f = b ^ c ^ d
      k = Machine.ptr(3395469782)
      if i < 20
        f = (b & c) | ((b ^ DIGEST_MASK32) & d)
        k = Machine.ptr(1518500249)
      elsif i < 40
        k = Machine.ptr(1859775393)
      elsif i < 60
        f = (b & c) | (b & d) | (c & d)
        k = Machine.ptr(2400959708)
      end
      t = (zr_digest_rotl32(a, 5) + f + e + k + zr_digest_word(w, i)) & DIGEST_MASK32
      e = d
      d = c
      c = zr_digest_rotl32(b, 30)
      b = a
      a = t
      i = i + 1
    end
    zr_digest_set(h, 0, (zr_digest_word(h, 0) + a) & DIGEST_MASK32)
    zr_digest_set(h, 1, (zr_digest_word(h, 1) + b) & DIGEST_MASK32)
    zr_digest_set(h, 2, (zr_digest_word(h, 2) + c) & DIGEST_MASK32)
    zr_digest_set(h, 3, (zr_digest_word(h, 3) + d) & DIGEST_MASK32)
    zr_digest_set(h, 4, (zr_digest_word(h, 4) + e) & DIGEST_MASK32)
  end

  #: (ptr, ptr) -> void
  def zr_sha256_block(h, p)
    # @type var hh: ptr
    # @type var s0: ptr
    # @type var s1: ptr
    k = zr_sha256_k()
    w = Machine.slot(512)
    i = 0
    while i < 16
      zr_digest_set(w, i, zr_digest_be32(p + (i * 4)))
      i = i + 1
    end
    while i < 64
      x = zr_digest_word(w, i - 15)
      y = zr_digest_word(w, i - 2)
      s0 = zr_digest_rotl32(x, 25) ^ zr_digest_rotl32(x, 14) ^ (x >> 3)
      s1 = zr_digest_rotl32(y, 15) ^ zr_digest_rotl32(y, 13) ^ (y >> 10)
      zr_digest_set(w, i, (zr_digest_word(w, i - 16) + s0 + zr_digest_word(w, i - 7) + s1) & DIGEST_MASK32)
      i = i + 1
    end
    a = zr_digest_word(h, 0)
    b = zr_digest_word(h, 1)
    c = zr_digest_word(h, 2)
    d = zr_digest_word(h, 3)
    e = zr_digest_word(h, 4)
    f = zr_digest_word(h, 5)
    g = zr_digest_word(h, 6)
    hh = zr_digest_word(h, 7)
    i = 0
    while i < 64
      s1 = zr_digest_rotl32(e, 26) ^ zr_digest_rotl32(e, 21) ^ zr_digest_rotl32(e, 7)
      t1 = (hh + s1 + ((e & f) ^ ((e ^ DIGEST_MASK32) & g)) + zr_digest_word(k, i) + zr_digest_word(w, i)) & DIGEST_MASK32
      s0 = zr_digest_rotl32(a, 30) ^ zr_digest_rotl32(a, 19) ^ zr_digest_rotl32(a, 10)
      t2 = (s0 + ((a & b) ^ (a & c) ^ (b & c))) & DIGEST_MASK32
      hh = g
      g = f
      f = e
      e = (d + t1) & DIGEST_MASK32
      d = c
      c = b
      b = a
      a = (t1 + t2) & DIGEST_MASK32
      i = i + 1
    end
    zr_digest_set(h, 0, (zr_digest_word(h, 0) + a) & DIGEST_MASK32)
    zr_digest_set(h, 1, (zr_digest_word(h, 1) + b) & DIGEST_MASK32)
    zr_digest_set(h, 2, (zr_digest_word(h, 2) + c) & DIGEST_MASK32)
    zr_digest_set(h, 3, (zr_digest_word(h, 3) + d) & DIGEST_MASK32)
    zr_digest_set(h, 4, (zr_digest_word(h, 4) + e) & DIGEST_MASK32)
    zr_digest_set(h, 5, (zr_digest_word(h, 5) + f) & DIGEST_MASK32)
    zr_digest_set(h, 6, (zr_digest_word(h, 6) + g) & DIGEST_MASK32)
    zr_digest_set(h, 7, (zr_digest_word(h, 7) + hh) & DIGEST_MASK32)
  end

  #: (ptr, ptr) -> void
  def zr_sha512_block(h, p)
    # @type var hh: ptr
    # @type var s0: ptr
    # @type var s1: ptr
    k = zr_sha512_k()
    ones = Machine.ptr(0 - 1)
    w = Machine.slot(640)
    i = 0
    while i < 16
      zr_digest_set(w, i, zr_digest_be64(p + (i * 8)))
      i = i + 1
    end
    while i < 80
      x = zr_digest_word(w, i - 15)
      y = zr_digest_word(w, i - 2)
      s0 = zr_digest_rotr64(x, 1) ^ zr_digest_rotr64(x, 8) ^ (x >> 7)
      s1 = zr_digest_rotr64(y, 19) ^ zr_digest_rotr64(y, 61) ^ (y >> 6)
      # SHA-512 adds modulo 2**64.
      zr_digest_set(w, i, Machine.uadd_wrap(Machine.uadd_wrap(Machine.uadd_wrap(zr_digest_word(w, i - 16), s0), zr_digest_word(w, i - 7)), s1))
      i = i + 1
    end
    a = zr_digest_word(h, 0)
    b = zr_digest_word(h, 1)
    c = zr_digest_word(h, 2)
    d = zr_digest_word(h, 3)
    e = zr_digest_word(h, 4)
    f = zr_digest_word(h, 5)
    g = zr_digest_word(h, 6)
    hh = zr_digest_word(h, 7)
    i = 0
    while i < 80
      s1 = zr_digest_rotr64(e, 14) ^ zr_digest_rotr64(e, 18) ^ zr_digest_rotr64(e, 41)
      ch = (e & f) ^ ((e ^ ones) & g)
      t1 = Machine.uadd_wrap(Machine.uadd_wrap(Machine.uadd_wrap(Machine.uadd_wrap(hh, s1), ch), zr_digest_word(k, i)), zr_digest_word(w, i))
      s0 = zr_digest_rotr64(a, 28) ^ zr_digest_rotr64(a, 34) ^ zr_digest_rotr64(a, 39)
      t2 = Machine.uadd_wrap(s0, (a & b) ^ (a & c) ^ (b & c))
      hh = g
      g = f
      f = e
      e = Machine.uadd_wrap(d, t1)
      d = c
      c = b
      b = a
      a = Machine.uadd_wrap(t1, t2)
      i = i + 1
    end
    zr_digest_set(h, 0, Machine.uadd_wrap(zr_digest_word(h, 0), a))
    zr_digest_set(h, 1, Machine.uadd_wrap(zr_digest_word(h, 1), b))
    zr_digest_set(h, 2, Machine.uadd_wrap(zr_digest_word(h, 2), c))
    zr_digest_set(h, 3, Machine.uadd_wrap(zr_digest_word(h, 3), d))
    zr_digest_set(h, 4, Machine.uadd_wrap(zr_digest_word(h, 4), e))
    zr_digest_set(h, 5, Machine.uadd_wrap(zr_digest_word(h, 5), f))
    zr_digest_set(h, 6, Machine.uadd_wrap(zr_digest_word(h, 6), g))
    zr_digest_set(h, 7, Machine.uadd_wrap(zr_digest_word(h, 7), hh))
  end

  # RIPEMD-160's five boolean functions, selected by step.
  #: (word, ptr, ptr, ptr) -> ptr
  def zr_rmd160_f(j, x, y, z)
    m = DIGEST_MASK32
    if j < 16
      return x ^ y ^ z
    elsif j < 32
      return (x & y) | ((x ^ m) & z)
    elsif j < 48
      return (x | (y ^ m)) ^ z
    elsif j < 64
      return (x & z) | (y & (z ^ m))
    end
    x ^ (y | (z ^ m))
  end

  #: (word, bool) -> ptr
  def zr_rmd160_k(round, right)
    if right
      if round == 0
        return Machine.ptr(1352829926)
      elsif round == 1
        return Machine.ptr(1548603684)
      elsif round == 2
        return Machine.ptr(1836072691)
      elsif round == 3
        return Machine.ptr(2053994217)
      end
      return Machine.ptr(0)
    end
    if round == 0
      return Machine.ptr(0)
    elsif round == 1
      return Machine.ptr(1518500249)
    elsif round == 2
      return Machine.ptr(1859775393)
    elsif round == 3
      return Machine.ptr(2400959708)
    end
    Machine.ptr(2840853838)
  end

  #: (ptr, ptr) -> void
  def zr_rmd160_block(h, p)
    steps = zr_rmd160_steps()
    al = zr_digest_word(h, 0)
    bl = zr_digest_word(h, 1)
    cl = zr_digest_word(h, 2)
    dl = zr_digest_word(h, 3)
    el = zr_digest_word(h, 4)
    ar = al
    br = bl
    cr = cl
    dr = dl
    er = el
    j = 0
    while j < 80
      xl = zr_digest_le32(p + (Machine.u8(Machine.load8(steps + j, 0)) * 4))
      t = (zr_digest_rotl32((al + zr_rmd160_f(j, bl, cl, dl) + xl + zr_rmd160_k(j / 16, false)) & DIGEST_MASK32, Machine.u8(Machine.load8(steps + 160 + j, 0))) + el) & DIGEST_MASK32
      al = el
      el = dl
      dl = zr_digest_rotl32(cl, 10)
      cl = bl
      bl = t
      xr = zr_digest_le32(p + (Machine.u8(Machine.load8(steps + 80 + j, 0)) * 4))
      t = (zr_digest_rotl32((ar + zr_rmd160_f(79 - j, br, cr, dr) + xr + zr_rmd160_k(j / 16, true)) & DIGEST_MASK32, Machine.u8(Machine.load8(steps + 240 + j, 0))) + er) & DIGEST_MASK32
      ar = er
      er = dr
      dr = zr_digest_rotl32(cr, 10)
      cr = br
      br = t
      j = j + 1
    end
    t = (zr_digest_word(h, 1) + cl + dr) & DIGEST_MASK32
    zr_digest_set(h, 1, (zr_digest_word(h, 2) + dl + er) & DIGEST_MASK32)
    zr_digest_set(h, 2, (zr_digest_word(h, 3) + el + ar) & DIGEST_MASK32)
    zr_digest_set(h, 3, (zr_digest_word(h, 4) + al + br) & DIGEST_MASK32)
    zr_digest_set(h, 4, (zr_digest_word(h, 0) + bl + cr) & DIGEST_MASK32)
    zr_digest_set(h, 0, t)
  end

  # Compresses each whole block of `data` with algorithm `algo` into `state`.
  #: (value, value, value) -> value
  def zr_digest_blocks(algo, state, data)
    a = zr_fix2long(algo)
    size = 64
    if a == DIGEST_SHA512
      size = 128
    end
    h = RString[state].ptr
    p = RString[data].ptr
    n = RString[data].len
    if a == DIGEST_SHA256 && zr_os_sha256_blocks(h, p, n - (n % 64))
      return Machine.value(QNIL)
    end
    at = 0
    while at + size <= n
      if a == DIGEST_MD5
        zr_md5_block(h, p + at)
      elsif a == DIGEST_SHA1
        zr_sha1_block(h, p + at)
      elsif a == DIGEST_SHA256
        zr_sha256_block(h, p + at)
      elsif a == DIGEST_SHA512
        zr_sha512_block(h, p + at)
      else
        zr_rmd160_block(h, p + at)
      end
      at = at + size
    end
    Machine.value(QNIL)
  end
